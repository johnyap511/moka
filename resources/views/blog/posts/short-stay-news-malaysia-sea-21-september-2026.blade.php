    <h2>Haze: over 30 areas nationwide reported unhealthy air this week</h2>
    <p>
        The Department of Environment recorded 30 areas with unhealthy Air Pollutant Index readings on 17
        September, rising to 35 the next day and still at 32 on 20 September, Malay Mail reported. Sarawak was
        hit hardest — Serian IPD read 173 on the 20th — with Putrajaya, Shah Alam, Nilai, Seremban and parts of
        Johor, Sabah and Melaka also unhealthy. The Jakarta Post reported the same week that bad weather was
        delaying Japanese firefighting helicopters sent to West Kalimantan, the worst-hit source region.
    </p>
    <p>
        <strong>For owners:</strong> guests notice haze before they notice your listing photos. We go through
        what to check and what to tell guests in
        <a href="/blog/southeast-asia-haze-2026-short-stay-hosting-guide">our full guide this week</a>.
    </p>

    <h2>Sabah's arrivals are up, not down</h2>
    <p>
        Sabah tourist arrivals rose 4.1% from January to August compared with the same period last year,
        assistant tourism minister Dr Andi Md Shamsureezal Mohd Sainal said at the Matta Fair Sabah opening on
        20 September, Malay Mail reported. International arrivals were up 6.9% and domestic visitors up 2.1%.
        The minister was responding directly to talk that the state's tourism sector was slowing.
    </p>
    <p>
        <strong>For owners:</strong> if you manage a unit in Kota Kinabalu or elsewhere in Sabah, the demand
        picture is better than the rumours suggest — worth checking your rates are not underpriced against it.
    </p>

    <h2>RTS Link: the Singapore side is built</h2>
    <p>
        Singapore's Land Transport Authority posted photos on 4 September of the completed Woodlands North
        station for the Johor Bahru–Singapore RTS Link, The Star reported on 15 September. On the Malaysian
        side, transport minister Anthony Loke said on 18 August that the link and the Bukit Chagar immigration
        complex have entered testing and commissioning, with a joint opening date and fare still to be
        announced. The 4km link is designed to carry up to 10,000 passengers an hour in each direction.
    </p>
    <p>
        <strong>For owners:</strong> a fare and opening date have not been set, so it is still too early to
        price around the launch — but a Johor Bahru unit within reach of Bukit Chagar is worth flagging in your
        listing description now, ahead of 2027.
    </p>

    <h2>40,000 visitors expected for a three-day festival on Melaka's coast</h2>
    <p>
        The Melaka Straits and River Arts Festival (FSSSM 2026) ran from 19 to 21 September at Dataran Pantai
        Tanjung Bidara in Alor Gajah, the ninth cultural tourism programme staged this year under Visit
        Malaysia 2026, Bernama reported. Organisers anticipated around 40,000 visitors across the three days for
        performances and cultural demonstrations themed around the Straits of Melaka's history as a meeting
        point of cultures.
    </p>
    <p>
        <strong>For owners:</strong> a one-off festival weekend on the mainland side of Melaka is a smaller,
        shorter demand spike than a Georgetown or KL event — useful for a Sunday-night rate bump rather than a
        multi-night minimum stay.
    </p>

    <h2>Even a duathlon had to work around the haze</h2>
    <p>
        Powerman Malaysia 2026, the duathlon held at Dataran Putrajaya from 18 to 20 September and targeting up
        to 5,000 participants, activated its air-quality contingency plan this week: the PowerKids race was
        cancelled outright because of unhealthy conditions, while the main Sunday races went ahead subject to
        readings on the day, The Star reported on 18 September.
    </p>
    <p>
        <strong>For owners:</strong> if you manage a unit near an outdoor event this month, check the
        organiser's own contingency plan, not just the forecast — a cancelled or shortened event can undercut a
        rate you set for full attendance.
    </p>

