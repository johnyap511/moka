        Five stories from the past week that matter if you own a short-stay unit in Malaysia: Formula 1 is
        back at Sepang after nine years, the Kuala Lumpur Marathon and Le Tour de Langkawi shared the same
        weekend, and Budget 2027 has turned into a tug-of-war between Airbnb, the hotel industry and Tourism
        Malaysia. One line on each of what it means for you.
    </p>

    <h2>Formula 1 returns to Sepang: Verstappen wins a rain-delayed race</h2>
    <p>
        Red Bull's Max Verstappen won the Gulf Air Bahrain Grand Prix at Sepang International Circuit on
        4 October, his first victory of the season, after the start was pushed back an hour and 40 minutes
        by heavy rain. Mercedes' Kimi Antonelli finished second and Ferrari's Lewis Hamilton third, after
        George Russell retired from third place with five laps left. It was Formula 1's first Malaysian race
        since 2017, relocated to Sepang after the original Bahrain venue could not host it this year. The
        series moves on to a night race in Singapore next weekend.
    </p>
    <p>
        <strong>For owners:</strong> the demand we wrote about in August and September has now been tested
        for real. If your unit is near KLIA, Cyberjaya or Putrajaya, check what the weekend actually earned
        against our <a href="/blog/f1-sepang-2026-short-stay-pricing-guide">pricing plan</a> and keep the
        same playbook ready for MotoGP later this year.
    </p>

    <h2>The same weekend: Le Tour de Langkawi's 30th edition and the KL Marathon</h2>
    <p>
        Malaysia ran three marquee events within days of each other. Le Tour de Langkawi's 30th edition
        covered eight stages and 1,265.8km across the peninsula between 27 September and 4 October, and the
        Kuala Lumpur Standard Chartered Marathon's full and half marathon categories ran on 4 October,
        alongside the F1 weekend. Organisers and tourism officials have taken to calling the cluster a
        "mega sports weekend" rather than promoting each event on its own.
    </p>
    <p>
        <strong>For owners:</strong> wherever your unit sits — Langkawi, Cameron Highlands, Genting, or
        central KL — one of these three events likely passed close to it this week. Note which one, and
        block it on your calendar a year ahead next time.
    </p>

    <h2>Airbnb asks for one national short-stay guideline ahead of Budget 2027</h2>
    <p>
        Airbnb's Southeast Asia head of public policy, Shanta Arul, called on the government to set national
        Short-Term Rental Accommodation (STRA) guidelines, arguing that Airbnb-related activity added
        RM8.3 billion to Malaysia's GDP and supported 108,300 jobs in 2025. The company also wants expanded
        access to the Gamelan and Tekun Nasional grant schemes for host compliance and digital literacy, and
        a review of the Tourism Industry Act 1992. Budget 2027 is tabled on 9 October.
    </p>
    <p>
        <strong>For owners:</strong> a single national guideline would replace the current state-by-state
        patchwork — but it is a request, not yet policy. We go through what is realistic by budget day in
        this week's feature.
    </p>

    <h2>Hotels want short-stay operators held to the same rules</h2>
    <p>
        The Malaysian Association of Hotels, through president Christina Toh, asked Budget 2027 to bring in
        stricter regulation of short-term rentals to "level the playing field" with licensed hotels, alongside
        relief on the sales and service tax (SST), electricity tariffs and Fire and Rescue Department fees.
        The Budget and Business Hotel Association separately asked for the SST registration threshold to rise
        from RM500,000 to RM1.5 million, saying gross revenue does not reflect a hotel's actual profit.
    </p>
    <p>
        <strong>For owners:</strong> this cuts the opposite way from Airbnb's ask. If Budget 2027 leans
        toward the hotel industry's position, expect tighter compliance talk rather than clearer rules.
    </p>

    <h2>Malaysia passed 21.1 million visitors in the first half, eyeing 47 million for the year</h2>
    <p>
        Tourism Malaysia recorded 21.1 million international arrivals between January and June 2026, up
        2.5% on the same period in 2025, and is asking for a bigger Budget 2027 allocation to reach its
        47-million target under the Visit Malaysia campaign, now extended to 2027 because of Middle
        East-related disruption to travel patterns. Tourism accounts for around 15% of GDP.
    </p>
    <p>
        <strong>For owners:</strong> demand is still climbing. The question for your unit is not whether
        visitors are coming, but whether your listing, pricing and compliance are ready for them.
    </p>

