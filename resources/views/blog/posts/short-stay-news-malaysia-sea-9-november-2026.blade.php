    <h2>Floods close in on Kelantan, Pahang, Selangor and Perak</h2>
    <p>
        The National Flood Forecasting Centre warned on 8 November that continuous heavy rain
        would bring flooding to nine Kelantan districts (Kota Bharu, Tumpat, Bachok, Machang,
        Pasir Mas, Pasir Puteh, Tanah Merah, Kuala Krai and Jeli) and three Pahang districts
        (Kuantan, Pekan and Rompin), with the warning running until Wednesday 11 November.
        Bernama reported two days earlier that Selangor already had 1,160 evacuees across ten
        relief centres in Kuala Selangor, Shah Alam and Klang, while Perak had 83 people sheltering
        in Hilir Perak and Manjung after overnight floods and a storm.
    </p>
    <p>
        <strong>For owners:</strong> if your unit sits in any of these districts, or along the
        Kuala Selangor to Klang corridor, check road access before confirming this week's arrivals
        and make sure guests know how to reach you if a relief order is issued nearby.
    </p>

    <h2>Penang halves its short-stay licence fee for 2027</h2>
    <p>
        Penang's local government committee chairman H'ng Mooi Lye said on 3 November that
        amendments to the Private Short-term Accommodation By-Laws 2026, taking effect
        1 January 2027, cut the annual licence fee from RM1,000 to RM500 for units with up to
        three rooms, and replace the flat RM1,800 accommodation (TIP) fee with a scale running
        from RM400 for one room to RM1,800 for five to ten rooms. Penang Malaysia Homestay/
        Short-Stay Operators Association chairman Lydia Tan welcomed the cut and is separately
        asking for one licence to cover up to ten units, a request the state has not yet agreed to.
    </p>
    <p>
        <strong>For owners:</strong> the cut only helps if you already applied before the grace
        period ended on 1 November. Our full breakdown of the new fees, and what still has not
        changed, is <a href="/blog/penang-short-stay-fee-changes-2027">here</a>.
    </p>

    <h2>The Weeknd's KL finale draws 130,000, strains transport</h2>
    <p>
        The Weeknd closed his five-year After Hours Til Dawn tour with two sold-out nights at TM
        National Stadium, Bukit Jalil, on 4 and 5 November, with Live Nation Malaysia estimating
        around 65,000 fans a night. Train operating hours were extended to 12.30am to clear the
        post-show crowd, though organisers said the extension was limited by "tight operational
        schedules," and reports described a rough scramble for transport once both shows let out.
    </p>
    <p>
        <strong>For owners:</strong> if your unit sits along the line into Bukit Jalil, build in a
        later check-in window after a big show weekend and tell guests the extended train hours
        are not a guarantee of a quick ride home.
    </p>

    <h2>Thailand's short-haul numbers climb, Malaysia still its No. 2 market</h2>
    <p>
        Thailand logged 25.46 million international arrivals from January to October 2026, Nation
        Thailand reported on 2 November, still 4.59% behind the same period last year, though
        short-haul arrivals for 25 to 31 October rose 3.14% week on week to 311,508. Malaysia
        supplied 61,842 of those arrivals, the week's single largest source market, and 3.23
        million year to date, second only to China.
    </p>
    <p>
        <strong>For owners:</strong> Malaysians are still travelling in the region at a steady
        clip, a reassuring sign if part of your occupancy depends on domestic wallets rather than
        long-haul recovery.
    </p>

    <h2>Kota Kinabalu's airport debate resurfaces</h2>
    <p>
        Aviation experts told a Chartered Institute of Logistics and Transport forum in Kota
        Kinabalu on 8 November that KKIA, which has averaged 4.1% annual passenger growth over 21
        years and carried about nine million passengers last year, is running out of room on its
        current site. Former CAAM chief executive Chester Voo argued for a new airport and
        aerotropolis elsewhere, while civil aviation consultant Edward Clayton set out
        on-site expansion options, including a second runway on reclaimed land. The federal
        government's position since 2024 has been to expand KKIA where it stands, not to build a
        replacement.
    </p>
    <p>
        <strong>For owners:</strong> nothing changes immediately, but if your unit is in or near
        Kota Kinabalu, this is worth tracking. Airport capacity is the ceiling on how many
        visitors the city can take.
    </p>

