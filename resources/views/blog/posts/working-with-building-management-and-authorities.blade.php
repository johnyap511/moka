    <p class="blog-lede">
        The hosts who last in Malaysia are not the ones with the best photos. They are the ones the
        building management does not want to get rid of. Short-term stays live or die on the
        goodwill of the JMB, the security desk and the local council. Here is how to keep all three
        on your side.
    </p>

    <h2>Start with the fact the building holds the power</h2>
    <p>
        In October 2020 the Federal Court decided <em>Innab Salil v Verve Suites Mont' Kiara</em>. A
        management corporation had passed a house rule banning short-term rentals, and unit owners
        argued the building's commercial title allowed them to let nightly. The court sided with the
        building: a JMB or MC can prohibit short-term stays through by-laws passed by special
        resolution, whatever the title says.
    </p>
    <p>
        That single decision shapes everything. Your right to host is not something the platform
        gives you or the title guarantees. It is something the building allows, and can withdraw at
        a general meeting with 75 percent of the vote. Treat the management body as your most
        important business partner, because it is.
    </p>

    <h2>Know which rules apply to your unit</h2>
    <p>There are three layers, and they stack.</p>
    <ul>
        <li><strong>The building's by-laws and house rules.</strong> These govern guests, visitors,
            move-in procedures, noise, parking and the pool. They apply to everyone, tenants and
            guests included, and you are responsible for your guests' compliance.</li>
        <li><strong>The local council.</strong> Penang now licenses short-term units under its 2026
            by-laws, with the island limited to commercial-titled buildings. Kuala Lumpur, Selangor,
            Johor and Sabah each take their own approach, and the national short-term rental guideline
            from the Housing and Local Government Ministry is still being finalised. Check the
            council's position for your address, and check again each year.</li>
        <li><strong>The platform's own rules.</strong> Airbnb and Booking.com require you to comply
            with local law and will remove listings on complaint from a management body.</li>
    </ul>

    <h2>Get consent properly, and keep it</h2>
    <ol>
        <li>Read the current house rules before you buy furniture. If short-term stays are banned,
            the answer is no, not "quietly".</li>
        <li>If the rules are silent, ask the JMB or MC in writing. Silence is not consent, and a
            building that discovers your listing on its own starts from a position of distrust.</li>
        <li>Where a vote is needed, help the management body run it. Draft the resolution, propose
            sensible conditions, and turn up. A well-run building will often say yes to hosts who
            offer a registration process, a guest cap and a contact number.</li>
        <li>Keep the paper. Minutes, the resolution, your registration, and any council licence.
            You will be asked for them by the next committee.</li>
    </ol>

    <h2>Give the building what it actually wants</h2>
    <p>
        Management bodies do not object to guests. They object to not knowing who is in the
        building, to noise at 2am, and to owners who are unreachable when something goes wrong.
        Remove those three problems and most of the friction disappears.
    </p>
    <ul>
        <li><strong>Register every guest.</strong> Name, contact number, dates, and the number of
            people. Send it to the security desk before check-in, every time, without being asked.</li>
        <li><strong>One phone number that answers.</strong> Give the management office and the guard
            house a line that is picked up at night. Complaints that are handled in ten minutes do not
            reach the AGM.</li>
        <li><strong>Access that can be switched off.</strong> Smart locks and access cards issued per
            stay, not permanent keys handed around. When a stay ends, access ends.</li>
        <li><strong>A guest cap and no-party rule</strong>, written into the listing, the house rules
            card in the unit, and the booking message. Screen bookings that do not fit the unit.</li>
        <li><strong>Pay what the rules ask.</strong> Some buildings charge hosts a higher service fee,
            a registration fee, or a deposit. Pay it on time. It is far cheaper than a ban.</li>
    </ul>

    <h2>Work with the council, not around it</h2>
    <ul>
        <li>Where registration or a licence exists, get it. In Penang that means applying to MBPP or
            MBSP with the building's consent before the 1 November 2026 deadline.</li>
        <li>Keep a guest register you can produce. Councils and police ask for it after incidents.</li>
        <li>Follow the fire and safety basics the licence assumes: smoke detector, extinguisher,
            clear exits, a printed emergency sheet in the unit.</li>
        <li>If your unit cannot be licensed where it stands, change the model. Monthly furnished stays
            under a tenancy agreement are outside most short-stay definitions and keep the unit
            earning without putting your building relationship at risk.</li>
    </ul>

    <h2>What a good relationship looks like in practice</h2>
    <p>
        In the buildings where MOKA operates, the management office has our registration sheet
        before each arrival, our operations line on the wall of the guard house, and a named person
        to call. Guests receive the house rules twice, once at booking and once at the door, and a
        stay that breaks them is ended. When the committee changes, we introduce ourselves again.
        None of that is complicated. It is simply done every time, which is what separates the hosts
        who are still operating after five years from the ones who were voted out.
    </p>
