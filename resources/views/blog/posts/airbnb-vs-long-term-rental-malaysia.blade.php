    <h2>Which units actually suit short stays</h2>
    <p>Short-stay demand is far more location-sensitive than long-term demand. It tends to work when:</p>
    <ul>
        <li>The unit is close to something people travel <em>for</em> — a business district, a
            hospital, a university, a transport hub, or a genuine tourist draw.</li>
        <li>The building has facilities guests value: a pool, a gym, reliable lifts, and a lobby
            that does not embarrass the photos.</li>
        <li>Check-in can be handled smoothly, ideally without a person waiting at the door.</li>
        <li>The building's management permits it.</li>
    </ul>
    <p>
        It works poorly for units in purely residential suburbs with no traveller demand, in
        buildings with hostile management, or where access requires an escort through security
        every time.
    </p>

    <div class="blog-callout">
        <p>
            <strong>The by-law question decides everything.</strong> Before modelling any numbers,
            confirm with your JMB or MC whether short-stay letting is permitted, and whether a
            minimum stay applies. Some Malaysian buildings ban it, some cap it, and enforcement
            has tightened in several areas. This single answer can remove the choice entirely.
        </p>
    </div>

    <h2>The risk profiles are different, not just the returns</h2>
    <p>
        A long-term tenancy concentrates risk: one tenant, one payment, and a bad one costs you
        months. Short stays spread it across many guests — a single bad night is a rounding error
        — but expose you to demand risk instead. A quiet season, a new competitor building, or a
        drop in travel shows up in your income immediately.
    </p>
    <p>
        Owners who need predictable cash flow to service a loan often value the tenancy's
        certainty more than the extra upside. Owners with buffer, or with a unit in genuinely
        strong demand, usually do better on short stays.
    </p>

    <h2>A reasonable way to decide</h2>
    <ol>
        <li>Confirm the building allows it.</li>
        <li>Find out what comparable units nearby actually achieve — occupancy and nightly rate,
            not headline best-case figures.</li>
        <li>Subtract the real running costs, including furnishing amortised over a few years.</li>
        <li>Compare that against a realistic long-term rent for the same unit.</li>
        <li>Decide whether the difference is worth the extra operational load — and if it is, whether
            you want to carry that load or hand it to someone else.</li>
    </ol>
    <p>
        If the two numbers land close together, take the tenancy. Short-stay only earns its
        complexity when it wins clearly.
    </p>
