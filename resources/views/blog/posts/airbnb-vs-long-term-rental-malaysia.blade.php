    <p class="blog-lede">
        Short-stay letting usually produces a bigger gross number than a long-term tenancy. It
        also costs considerably more to run, and it does not suit every unit. The question is not
        which earns more in theory, but which earns more net, in your building, with your
        tolerance for admin.
    </p>

    <h2>Compare net, never gross</h2>
    <p>
        A long-term tenancy at RM2,500 a month is close to RM2,500 in your pocket. Short-stay
        revenue is not, because several costs sit between the booking and your account: platform
        commission, cleaning, linen and consumables, utilities and internet (which the guest does
        not pay), higher wear, and management if you use it.
    </p>
    <p>
        The comparison only makes sense after those come out. An owner comparing a short-stay
        gross figure against a long-term net figure will always reach the wrong conclusion.
    </p>

