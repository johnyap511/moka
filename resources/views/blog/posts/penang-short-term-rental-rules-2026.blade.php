    <p class="blog-lede">
        Penang is the first state in Malaysia with a law, not just a guideline, for short-term stays.
        The Private Short-term Accommodation By-Laws 2026 came into force on 1 August 2026, with a
        grace period to 1 November 2026 for operators to apply for a licence. If you own or run a
        unit in Penang, here is what changes, what it costs, and what to do before the deadline.
    </p>

    <h2>How Penang got here</h2>
    <p>
        The island council, MBPP, issued its first short-term rental guidelines in May 2023: private
        residential units were off limits, commercial high-rises could operate with the building's
        consent, and operators had to register with the council. Complaints kept coming. Between 2020
        and March 2026 MBPP logged 364 nuisance and safety complaints tied to unlicensed short-term
        units, and the mainland council MBSP another 24. The state's answer was to turn the guideline
        into by-laws with licences, fees and enforcement powers for both councils.
    </p>

    <h2>What counts as a TIP</h2>
    <p>
        The by-laws use the term <em>Tempat Inap Persendirian</em>, or TIP: paid accommodation
        provided without a tenancy agreement for a period of up to six consecutive months. That
        covers Airbnb and Booking.com nightly stays, weekly and monthly furnished stays, and
        corporate housing. A twelve-month tenancy is not a TIP.
    </p>

    <h2>Which properties can operate</h2>
    <p>The answer depends on which side of the bridge you are on.</p>
