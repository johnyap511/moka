    <p>
        Some premises are excluded everywhere: government and statutory-body property, healthcare and
        childcare centres, workers' hostels, private education institutions, low-cost and
        low-medium-cost housing, and controlled-price homes.
    </p>
    <p>
        For most of our Penang owners the practical line is the land title. A serviced apartment on a
        commercial title in George Town or Bayan Lepas can be licensed. A condominium on a residential
        title on the island cannot, whatever its house rules say.
    </p>

    <h2>The building has to say yes first</h2>
    <p>
        A licence needs the consent of the building's management body, the JMB or MC. That consent is
        a special resolution, at least 75 percent of valid votes at a general meeting. The management
        body can refuse, and there is no appeal against a refusal. Consent is not permanent either:
        owners apply to the JMB or MC again each January, and the building reports its short-term
        units to the Commissioner of Buildings and the council every December.
    </p>
    <p>
        This mirrors the Federal Court's 2020 decision in <em>Innab Salil v Verve Suites</em>, which
        confirmed that a management body can ban short-term rentals through its house rules even in a
        commercial-titled building. Penang has written that principle into the licensing process.
    </p>

    <h2>What it costs</h2>
    <p>The fee schedule published with the by-laws in August 2026:</p>
    <ul>
        <li>RM50 application fee.</li>
        <li>Annual licence from RM1,000, covering up to three rooms, plus RM200 a year for each
            additional room, to a maximum of two more.</li>
        <li>RM1,800 a year accommodation fee per unit.</li>
    </ul>
    <p>
        So a typical two-bedroom unit is looking at roughly RM2,850 a year in council charges before
        anything else. On a unit earning RM5,000 a month that is about five percent of revenue. On a
        unit earning RM2,000 a month it is twelve percent, which changes the sums. Confirm the current
        schedule with MBPP or MBSP when you apply, as fees can be revised.
    </p>

    <h2>Deadlines and enforcement</h2>
    <ul>
        <li>1 August 2026: by-laws in force.</li>
        <li>1 November 2026: end of the grace period. Applications should be in before this date.</li>
        <li>After that, both councils can act against unlicensed units, and the by-laws give them the
            power to do so directly rather than through the building.</li>
    </ul>

    <h2>What to do now if you own a Penang unit</h2>
    <ol>
        <li>Check your title. Commercial or residential decides everything on the island.</li>
        <li>Ask your JMB or MC whether short-term stays have been approved by special resolution, and
            when the next general meeting is if not.</li>
        <li>Gather the paperwork: title or sale agreement, management consent, company registration
            if you operate through one, and the unit's floor plan for the room count.</li>
        <li>Apply to MBPP or MBSP before 1 November 2026.</li>
        <li>If your unit cannot be licensed, switch it to monthly furnished stays under a tenancy
            agreement, or a conventional long-term tenancy, rather than keep operating and wait for
            a complaint.</li>
    </ol>
