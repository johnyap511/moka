    <h2>Malaysia Cultural Festival packs Titiwangsa, MOTAC goes asking for funds</h2>
    <p>
        The six-day Malaysia Cultural Festival (Festival Budaya Malaysia) 2026 opened at Taman Tasik
        Titiwangsa in Kuala Lumpur on 13 September and runs to 16 September, Bernama reported, framed
        as part of the Visit Malaysia Year 2026-2027 campaign and featuring performances and heritage
        showcases from across the country, including Sabah and Sarawak. Tourism, Arts and Culture
        Minister Tiong King Sing said past editions of the festival, in Titiwangsa, Johor Bahru and
        Ipoh, drew 772,192 visitors and returned RM56.5 million, and said the ministry is now seeking
        budget allocations to help state governments upgrade existing tourist destinations and develop
        new ones.
    </p>
    <p>
        <strong>For owners:</strong> a free, multi-day festival in the city centre is a small but real
        reason for a Kuala Lumpur booking that week. If your unit is near Titiwangsa or on the way to
        it, it is worth a line in your listing while the festival is still current, and worth watching
        for more of these if the ministry's funding request lands.
    </p>

    <h2>Malaysia keeps its Muslim-friendly No. 1 for an 11th year</h2>
    <p>
        Malaysia retained the top spot in the Mastercard-CrescentRating Global Muslim Travel Index
        2026 for the eleventh consecutive year, Bernama reported on 12 September, as the government
        runs the fifth edition of Islamic Tourism Month this month to promote Muslim-friendly
        destinations, accommodation and products to domestic and international travellers.
    </p>
    <p>
        <strong>For owners:</strong> this is a large and returning segment, and a short-stay unit does
        not need a hotel's certification to serve it well. We go through what actually helps in
        <a href="/blog/muslim-friendly-hosting-malaysia-short-stay-guide">our guide this week</a>.
    </p>

    <h2>Unsold completed homes keep climbing, but the wider market holds up</h2>
    <p>
        The Valuation and Property Services Department's first-half 2026 property market report,
        covered by The Star on 10 September, put unsold completed residential units at 33,094 worth
        RM17.78 billion, up 8.6% on the previous half-year. Finance Minister II Datuk Seri Amir Hamzah
        Azizan said the wider market remained resilient, with 187,320 property transactions worth
        RM105.12 billion completed between January and June, and pointed to a steady 2.75% overnight
        policy rate as one reason financing has stayed stable for buyers.
    </p>
    <p>
        <strong>For owners:</strong> a rising overhang is a buyer's market for anyone shopping for a
        unit to run as a short-stay, but overhang and short-stay demand do not track each other.
        Location, near event venues and public transport, still decides whether a discounted unit will
        actually fill.
    </p>

    <h2>Thailand halves its visa-free stay to 30 days</h2>
    <p>
        From the evening of 14 September, Thailand's 60-day visa exemption for 93 nationalities ended,
        replaced by a tiered system: a 30-day exemption for 60 countries and territories, a 15-day
        exemption for two more (Mauritius and Seychelles), and visa-on-arrival for three others, the
        Tourism Authority of Thailand said, following orders published in the Royal Gazette on 31
        August. Land-border entries under the exemption are capped at twice a calendar year, except
        for travellers from Malaysia, Singapore, Brunei and Indonesia. Twenty-one nationalities that
        previously entered visa-free now need a visa.
    </p>
    <p>
        <strong>For owners:</strong> shorter Thai stays can push some multi-country Southeast Asia
        itineraries to spend the freed-up nights elsewhere. It is a small tailwind, not a strategy, but
        it is one more reason a flexible cancellation policy earns its keep this quarter.
    </p>

    <h2>Airbnb names a new head for Asia</h2>
    <p>
        Airbnb promoted Zhiqiu Kong to regional director for Asia, overseeing the company's business
        across China, Japan, Korea, India and Southeast Asia, TTG Asia reported on 15 September. Kong
        has been with Airbnb more than a decade in product, growth and strategy roles; Michael He moves
        up to country manager for China.
    </p>
    <p>
        <strong>For owners:</strong> regional leadership changes rarely move fast, but Kong now sits
        over the office that engages Southeast Asian governments on short-stay rules, Malaysia's
        included. Worth watching if MySTRA or KPKT get a new counterpart at the platform.
    </p>

