    <p class="blog-lede">
        Budget 2027, tabled by Prime Minister Anwar Ibrahim on 9 October 2026, carries more for short-stay
        owners than the usual tourism-ministry line items: a longer duty-free window for Langkawi and
        Labuan tied to a minimum stay, and a stamp duty and financing package for anyone still buying a
        unit. Here is what actually changes and what to do about it.
    </p>

    <h2>More money behind Visit Malaysia, now running through 2027</h2>
    <p>
        The government allocated RM935 million for tourism and culture, up from RM705 million in 2026,
        as the Visit Malaysia campaign is extended into 2027. The allocation funds promotional grants
        and tourism events, and a new International and Charter Flight Matching Grant is meant to help
        attract direct flight routes from China, India, Central Asia and Europe, extending also to
        cruise ships, ferries and tour buses carrying international visitors.
    </p>
    <p>
        <strong>For owners:</strong> more marketing spend and more new routes mean more unfamiliar
        guests discovering your area for the first time next year. Listings that answer basic
        first-timer questions, transport from the airport, nearest supermarket, checkout time, tend to
        convert this new demand better than listings that assume local knowledge.
    </p>

    <h2>Langkawi and Labuan: duty-free goes up, but only past 48 hours</h2>
    <p>
        The duty-free shopping allowance for visitors to Langkawi and Labuan rises to RM10,000, up from
        the previous limit, but it is conditional on a minimum stay of 48 hours. Anwar also said more
        Langkawi-made products would be exempted from import duty.
    </p>
    <p>
        <strong>For owners:</strong> if your unit is in Langkawi or Labuan, this is a direct nudge
        toward longer stays, not day trips or single-night stopovers. A three-night minimum stay policy,
        with the duty-free allowance mentioned in your listing description, turns a budget line into a
        selling point.
    </p>

    <h2>Stamp duty relief if you're still buying</h2>
    <p>
        For sale and purchase agreements signed between 1 January 2027 and 31 December 2030, first-time
        buyers get a full stamp duty exemption on the loan agreement and transfer instrument for homes
        up to RM500,000. For homes priced between RM500,000 and RM750,000, the first RM500,000 is fully
        exempt and the remaining amount gets a 50% exemption. The same exemption window, from 2027 to
        2030, also applies to rescue contractors or developers and original buyers in abandoned housing
        projects.
    </p>
    <p>
        <strong>For owners:</strong> the exemption applies by SPA signing date, not booking date. If you
        are close to signing on a unit you plan to run as a short-stay or monthly rental, waiting until
        after 1 January 2027 to sign could be worth the saving, depending on how the price and timeline
        otherwise compare.
    </p>

    <h2>A new guarantee scheme aimed at the self-employed</h2>
    <p>
        The Housing Credit Guarantee Scheme (SJKP) will offer up to RM20 billion in housing financing
        guarantees, targeted at helping 80,000 first-time buyers qualify, with particular attention to
        self-employed applicants without a fixed monthly income.
    </p>
    <p>
        <strong>We think</strong> this matters more for short-stay owners than it first appears: many
        hosts who run their unit as their main income have struggled to show banks a steady salary.
        A guarantee scheme built around that gap is worth asking your bank about directly once SJKP's
        application process is published.
    </p>

