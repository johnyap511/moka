    <h2>What to do now</h2>
    <ol>
        <li>If your unit is in Langkawi or Labuan, set or raise your minimum stay to at least three
            nights and mention the duty-free allowance in your listing.</li>
        <li>If you are negotiating a purchase, ask your lawyer whether delaying the SPA signing to
            2027 changes your stamp duty bill, and weigh that against any price or timeline cost of
            waiting.</li>
        <li>If you are self-employed and have been turned down for a mortgage on income grounds, watch
            for the SJKP scheme's application details and ask your bank whether it participates.</li>
        <li>Review your listing description and photos against what a first-time visitor to Malaysia,
            rather than a repeat guest, would need to know.</li>
    </ol>
