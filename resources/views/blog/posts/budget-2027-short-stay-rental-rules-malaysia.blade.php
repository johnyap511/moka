    <h2>What is realistic by 9 October</h2>
    <p>
        Budgets fund things; they rarely finish a planning guideline. The PLANMalaysia STRA guideline, as we
        <a href="/blog/short-stay-news-malaysia-sea-16-september-2026">reported in September</a>, still has
        two approval steps ahead of it — Cabinet, then the National Council for Local Government — so a
        finished national rulebook on budget day would be unusually fast. What is more likely is money:
        a grant allocation Airbnb can point to as a partial win, or a tourism marketing budget for Tourism
        Malaysia's 47-million-arrival target. The SST threshold hotels are asking about is a tax-policy
        change that budgets do decide directly, so that is worth watching even though it targets hotels, not
        short-stay units, for now.
    </p>

