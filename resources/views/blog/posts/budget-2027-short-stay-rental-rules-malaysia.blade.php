    <p class="blog-lede">
        Budget 2027 is tabled on 9 October, and three groups have put competing asks on the table about
        short-stay rentals: Airbnb wants one national guideline, the hotel industry wants tighter rules on
        operators like you, and Tourism Malaysia wants a bigger marketing budget to chase 47 million
        visitors. Here is what each side is asking for, what is realistic by budget day, and what to do
        regardless of what gets announced.
    </p>

    <h2>What Airbnb is asking for</h2>
    <p>
        Airbnb's Southeast Asia head of public policy, Shanta Arul, told the government that Airbnb-related
        activity contributed an estimated RM8.3 billion to Malaysia's GDP in 2025, supported 108,300 jobs and
        generated nearly RM3 billion in labour income. Her Budget 2027 wishlist asks for a single set of
        national Short-Term Rental Accommodation (STRA) guidelines, so hosts face one standard instead of a
        different rule in every state; wider access to the Gamelan and Tekun Nasional grant schemes to help
        hosts with compliance, safety and digital literacy; and a review of the Tourism Industry Act 1992 to
        cover short-stay operators and licensed hotels under the same consumer-protection rules.
    </p>

    <h2>What the hotel industry wants instead</h2>
    <p>
        Hotels see the same gap and want it closed from the other direction. The Malaysian Association of
        Hotels, through president Christina Toh, asked Budget 2027 to bring in stricter regulation of
        short-term rentals to "level the playing field" with licensed hotels, which carry costs — safety
        inspections, fire certification, SST — that many short-stay operators do not. The Malaysia Budget and
        Business Hotel Association separately asked for the SST registration threshold to rise from
        RM500,000 to RM1.5 million, arguing that gross revenue does not reflect a hotel's actual profit. Both
        asks are about cost, not about banning short-stay units outright.
    </p>

    <h2>The patchwork these proposals are trying to fix</h2>
    <p>
        Both sides are reacting to the same problem: short-stay rules in Malaysia are set state by state and
        sometimes council by council, with no single federal standard.
    </p>
