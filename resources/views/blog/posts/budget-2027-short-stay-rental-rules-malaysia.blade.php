    <h2>What to do now</h2>
    <ul>
        <li>Keep your Penang, Selangor or DBKL registration current regardless of what Budget 2027 says — none of these proposals remove the existing requirements.</li>
        <li>On 9 October, check the budget speech for the SST threshold and any direct mention of a national STRA guideline or grant scheme.</li>
        <li>If you operate units in more than one state, keep each state's rules in a separate checklist — nothing in Budget 2027 will unify them overnight.</li>
