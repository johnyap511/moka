    <p>
        Check the live reading for your unit's area on the Department of Environment's APIMS portal before a
        guest checks in, the same way you would check the weather. It changes by the day and by the district —
        a unit in Kuala Lumpur can be moderate while one in Shah Alam is unhealthy on the same afternoon.
    </p>

    <h2>What guests will notice and ask</h2>
    <p>
        Expect three kinds of guest this haze season: travellers who did not know, travellers who saw the
        readings and are anxious, and travellers with an existing respiratory condition who need real
        information, not reassurance. Powerman Malaysia's own organisers gave a working example of how to
        communicate this well: The Star reported on 18 September that the event cancelled its children's race
        outright over unhealthy conditions while keeping the main Sunday races subject to readings on the day —
        a clear, specific call rather than a vague "we're monitoring the situation".
    </p>
    <p>
        <strong>For owners:</strong> copy that pattern. Tell a guest what the reading was as of your last check,
        not just that "there's some haze about".
    </p>

    <h2>What to change in the unit this week</h2>
    <ul>
        <li><strong>Windows and ventilation.</strong> If your air-conditioning has a fresh-air intake, close it
            during unhealthy readings and rely on recirculated, filtered air instead.</li>
        <li><strong>Air purifier.</strong> If you own more than one unit in a haze-prone area, this is the week
            it pays for itself; even a basic HEPA unit in the living area helps and gives you something concrete
            to mention in your listing.</li>
        <li><strong>Masks on hand.</strong> A small stock of N95 or KN95 masks at the unit costs little and is a
            visible, useful gesture for a guest who did not pack one.</li>
        <li><strong>Indoor alternatives.</strong> Have two or three indoor options ready to suggest — malls,
            museums, cafes — for a guest whose outdoor plans fall through.</li>
    </ul>

    <h2>What to say, and when</h2>
    <p>
        Message guests with a booking in the next seven days if their area's API has been in the unhealthy band
        more than once this week. Keep it short: the reading, what it means, and what you have done about it at
        the unit. Do not promise the haze will clear by a certain date — none of the reporting this week gives
        one, and the firefighting effort in Kalimantan is still being slowed by weather. If a guest wants to
        cancel or reschedule over air quality, we think a short-stay operator should treat that request kindly;
        a haze-driven cancellation is not the same as a change of mind.
    </p>

