    <p class="blog-lede">
        Haze from Indonesia's wildfires has kept large parts of Malaysia at unhealthy air quality for most of
        September, and it reached Singapore, Vietnam, Cambodia and Laos too. If you host guests anywhere on the
        peninsula, in Sarawak or in Sabah, this is now a live part of running your unit, not background news.
        Here is what the readings actually say, what guests will notice, and what to change this week.
    </p>

    <h2>What is happening</h2>
    <p>
        Indonesia is fighting forest and peatland fires across Sumatra and Kalimantan, driven by a severe
        drought this year. The Jakarta Post reported on 17 September that bad weather was delaying Japan
        Self-Defense Force helicopters sent to help fight the fires in West Kalimantan, one of the worst-hit
        provinces, and that the resulting haze had reached as far as Vietnam, Cambodia and Laos while still
        affecting Malaysia and Singapore.
    </p>
    <p>
        In Malaysia, the Department of Environment recorded 30 areas nationwide with unhealthy Air Pollutant
        Index readings on 17 September, rising to 35 on 18 September and still at 32 on 20 September, Malay
        Mail reported. Sarawak has been hit hardest — Serian IPD read 173 on 20 September, with Samarahan,
        Kuching, Sri Aman, Bintulu, Miri and Sibu all unhealthy too. On the peninsula, Putrajaya (161), Nilai
        (160), Shah Alam (157) and Seremban (156) were among the worst readings, alongside parts of Johor,
        Sabah and Melaka. Singapore's National Environment Agency reported a 24-hour PSI of 71 to 102 on 20
        September, moderate to unhealthy, with 1-hour PM2.5 readings of 24 to 73µg/m³.
    </p>

