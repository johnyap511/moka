    <h2>What is confirmed</h2>
    <p>
        The Malaysian Motorcycle Grand Prix runs 30 October to 1 November at Sepang, under a hosting
        contract the Malaysian government renewed for 2027 to 2031 at a Cabinet meeting on 15 April
        2026. SIC chief executive Azhan Shafriman Hanif said on 11 October that 80% of tickets had
        sold, with the race drawing extra interest from Moto3 rider Hakim Danish Ramli's debut season.
        The 2025 edition drew 190,977 spectators over three days; SIC is targeting 200,000 this year.
        Parking rates are being held at last year's level, and motorcycles will again be allowed into
        the circuit grounds.
    </p>

