        MotoGP returns to Sepang on 30 October to 1 November 2026, three weeks after the Formula 1
        Gulf Air Bahrain Grand Prix drew a record 261,000 spectators to the same circuit. Sepang
        International Circuit (SIC) says 80% of MotoGP tickets are already sold and is targeting
        200,000 visitors over the three days. Here is what is confirmed and a pricing plan for owners
