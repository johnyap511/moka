    <h2>Where the guests will stay</h2>
    <p>
        Sepang has little hotel stock of its own, so demand spills outward. The circuit sits next to
        KLIA, which makes units near the airport, in Cyberjaya and in Putrajaya the closest short-stay
        options. Kuala Lumpur city is roughly half an hour away by the KLIA Ekspres to KL Sentral and
        the circuit's own shuttle buses, and it is where the Friday and Sunday night crowd, less
        committed to being trackside both days, will mostly want to be. Serviced apartments around
        KLCC, Bukit Bintang and along the ERL line will fill first, as they did for F1.
    </p>

    <h2>A pricing plan for 29 October to 2 November</h2>
    <ol>
        <li><strong>Check your calendar today.</strong> If those dates are already sold at ordinary
            rates to a monthly or long booking, note it for next year and move on.</li>
        <li><strong>Turn off every discount</strong> across the window: weekly, monthly, last-minute
            and any channel promotion that auto-applies.</li>
        <li><strong>Set a three-night minimum</strong> from Thursday 29 October to Monday 2 November.
            MotoGP's biggest single-day crowd is the Sunday race, so do not leave the surrounding
            nights uncovered.</li>
        <li><strong>Price against the F1 weekend as your benchmark, then adjust down slightly.</strong>
            F1 pulled a record crowd; MotoGP's three-day target of 200,000 is close behind it, but the
            spend per visitor on a motorcycle race weekend tends to run a little lower. Raise again
            once the first bookings land.</li>
        <li><strong>Flag the access situation plainly.</strong> With motorcycles allowed into the
            circuit grounds and parking held at last year's rate, say in your listing whether you offer
            secure parking or are a short walk from the KLIA Ekspres or a shuttle stop; this is what
            got the most questions during the F1 weekend.</li>
        <li><strong>Hold back a unit if you manage more than one in the same building.</strong> Local
            fans, not just international visitors, are driving the 80% sell-through on tickets, and
            late local bookings for a near-sellout event tend to pay close to peak rate.</li>
    </ol>

