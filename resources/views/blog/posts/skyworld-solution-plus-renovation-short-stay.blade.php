    <h2>The order of operations</h2>
    <p>
        Doing these in the wrong order is what turns a two-month setup into a six-month one.
    </p>
    <ol>
        <li><strong>Defect inspection first.</strong> Log every defect during your defect liability
            period and get it rectified before renovation starts. Fixing a developer defect after
            you have tiled, painted or installed built-ins is dramatically more expensive, and you
            may forfeit the claim.</li>
        <li><strong>Confirm the building permits short stays.</strong> Ask the management office
            directly, in writing, and read the by-laws. This is the step that can invalidate the
            whole plan, so take it before you spend.</li>
        <li><strong>Arrange financing.</strong> If you are using MyDeco, approval takes time.
            Start it before you commit to a renovation schedule.</li>
        <li><strong>Design and renovate.</strong> Renovation windows in most buildings are
            restricted to weekday working hours, which lengthens timelines.</li>
        <li><strong>Furnish and style.</strong> Then photograph — properly, in daylight.</li>
        <li><strong>List and host.</strong></li>
    </ol>

    <h2>Renovating for guests is not renovating for yourself</h2>
    <p>
        The instinct is to furnish the unit the way you would want to live in it. Short-stay
        guests optimise for different things, and the differences are worth money:
    </p>
    <ul>
        <li><strong>Durability over delicacy.</strong> Every surface will be used by strangers who
            are not being careful. Light fabric sofas and glass-topped tables age badly.</li>
        <li><strong>Sleep quality above all.</strong> The mattress, the pillows, the blackout
            curtains and the air-conditioning are what reviews talk about. Spend here first.</li>
        <li><strong>Storage you can lock.</strong> One secured cupboard for linens and spares
            saves the cost of restocking a whole unit.</li>
        <li><strong>Lighting that photographs.</strong> Warm, layered lighting reads well in
            photos and in person. A single ceiling downlight does neither.</li>
        <li><strong>Enough of everything.</strong> Two of a thing for a two-bedroom unit is not
            enough — guests bring the number of people the listing sleeps.</li>
    </ul>

