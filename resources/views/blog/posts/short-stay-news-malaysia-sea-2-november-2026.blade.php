    <h2>KPKT's nationwide short-stay guideline heads toward Cabinet</h2>
    <p>
        Deputy Housing and Local Government Minister Aiman Athirah Sabu told the Dewan Rakyat on
        26 October that the Housing and Local Government Ministry, through PLANMalaysia, is
        finalising guidelines for short-term rental accommodation (STRA) with the Tourism, Arts
        and Culture Ministry, state governments and local authorities. Under the draft, only
        premises registered and fully compliant with local licensing conditions could operate
        legally, and strata buildings would remain governed by their JMB or MC under the Strata
        Management Act 2013. A proposed 180-night annual cap is still being assessed; a
        regulatory impact assessment has already been carried out. The guidelines go to Cabinet
        next, then the National Council for Local Government, before states and councils adopt
        them.
    </p>
    <p>
        <strong>For owners:</strong> no date is set, so nothing changes yet. But the direction is
        clear: local licensing will decide who can legally operate, and strata by-laws apply on
        top of that. Getting both in order now beats waiting for a federal deadline to force it.
    </p>

    <h2>Malaysia logs 32.2 million arrivals to September</h2>
    <p>
        Tourism, Arts and Culture Minister Tiong King Sing told the Dewan Rakyat on 27 October
        that Malaysia recorded 32.26 million international visitor arrivals from January to
        September 2026, up 2.4% on the same period last year. He put the tourism sector's
        contribution at RM323 billion, or 15.9% of the national economy.
    </p>
    <p>
        <strong>For owners:</strong> arrivals are still rising at the national level heading into
        the final quarter, which supports the occupancy outlook for the usual year-end travel
        season.
    </p>

    <h2>Penang's licence grace period has ended</h2>
    <p>
        The two-month grace period under Penang's Private Short-term Accommodation By-Laws 2026
        ended on 1 November, the deadline operators were given to apply for a local authority
        licence after the by-law took effect on 1 August. MBPP bars short-term rentals in all
        stratified residential buildings on the island; MBSP allows them in residential and
        commercial areas on the mainland. Operating without a licence after the deadline risks a
        fine of up to RM2,000, up to a year in jail, or both.
    </p>
    <p>
        <strong>For owners:</strong> if your Penang unit has not applied, the grace period is
        over. Our full guide to the by-laws, including which buildings qualify, is
        <a href="/blog/penang-short-term-rental-rules-2026">here</a>.
    </p>

    <h2>Thailand's weekly arrivals tick up, Malaysia its second-largest market</h2>
    <p>
        Thailand's tourism ministry logged 501,965 foreign arrivals for 18 to 24 October, up
        2.99% on the previous week. Malaysia was the second-largest source market that week with
        62,724 arrivals, behind China's 49,494 (itself down 24.17% on the same week last year)
        and ahead of India, Russia and the United States. Cumulative arrivals to 24 October stood
        at 24.93 million, still down 4.43% on the same period last year.
    </p>
    <p>
        <strong>For owners:</strong> Malaysians remain one of the first nationalities back
        travelling in the region. If you also track units or clients with exposure elsewhere in
        Southeast Asia, outbound Malaysian demand is worth watching alongside your own occupancy.
    </p>

    <h2>A sold-out stadium weekend lands in Kuala Lumpur</h2>
    <p>
        The Weeknd plays two sold-out nights at TM National Stadium, Bukit Jalil, on 4 and 5
        November. Booking data reported this month showed travel to Kuala Lumpur for 2 to 4
        November running at nearly 22 times the city's average daily booking volume for the
        month, with concertgoers booking an average of 95 days ahead.
    </p>
    <p>
        <strong>For owners:</strong> if your unit sits anywhere near Bukit Jalil or on a direct
        line into the city, this is not a normal weekend to leave at your usual rate. We've set
        out a full pricing plan in
        <a href="/blog/weeknd-bukit-jalil-2026-short-stay-pricing-guide">The Weeknd at Bukit Jalil: a pricing plan for KL owners</a>.
    </p>

