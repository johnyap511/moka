    <p class="blog-lede">
        Malaysia still has no single national law for short-stay operators. What it has is a patchwork
        of state and council rules, plus a national guideline that has sat in "final review" for
        months. Deputy Housing and Local Government Minister Aiman Athirah Sabu told the Dewan Rakyat
        on 26 October that the Short-Term Rental Accommodation (STRA) planning guideline is being
        finalised with the Tourism, Arts and Culture Ministry before it goes to Cabinet. Nothing here
        is law yet. The direction, though, is clear enough to plan around.
    </p>

    <h2>What the guideline would actually require</h2>
    <p>
        Under the draft, only premises that are registered and fully compliant with local authority
        licensing conditions could legally operate as short-term rentals. Strata properties would stay
        governed day to day by their Joint Management Body or Management Corporation under the Strata
        Management Act 2013, on top of whatever the national guideline sets. Enforcement would draw on
        existing laws already in use: the Town and Country Planning Act 1976, the Street, Drainage and
        Building Act 1974, and local by-laws. A 180-night annual cap is still being assessed nationally,
        separate from any cap an individual state sets for itself.
    </p>

    <h2>The new piece: platforms would have to verify and delist</h2>
    <p>
        The clearest new detail to emerge so far is about platforms, not hosts. The government wants
        booking platforms to run an automatic licence-status check before any premises is listed, and
        to carry responsibility for delisting premises that are unlicensed or breach local authority
        conditions. Local authorities and enforcement agencies would be able to pursue operators who
        keep listing anyway and have those listings blocked at the platform level. None of this has a
        start date yet, but it is the mechanism most likely to actually bite once it does: a licence
        problem would show up as a delisted calendar, not just a letter from the council.
    </p>

    <h2>Where each state actually stands today</h2>
    <p>
        The guideline is still federal and still pending. Until it lands, your unit is governed by
        whatever your state and council already have in force, and that varies a lot.
    </p>
