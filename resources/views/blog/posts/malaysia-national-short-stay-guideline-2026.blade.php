    <h2>What happens next, and when</h2>
    <p>
        The guideline's path is public even if the dates are not: final review with MOTAC, then Cabinet,
        then the National Council for Local Government (MNKT) for agreement, then adoption by state and
        local authorities. No stage has a published deadline. The same minister gave an almost identical
        update on 6 October, which tells you how much ground was covered in the month after: not much.
        Expect this to move in steps measured in months, not weeks.
    </p>

    <h2>What to do now</h2>
    <ul>
        <li>Check your state's and council's current rule, not the national draft. A Selangor or Johor
            unit is not covered by anything specific to short-stay yet; a Penang unit already is.</li>
        <li>If your unit is in George Town's heritage zone, expect a TIP ratio by zone on top of the
            August by-law. Ask MBPP or a licensing agent before you renew or expand.</li>
        <li>If you list in a strata building anywhere in the country, your JMB or MC's by-laws apply
            regardless of what the national guideline eventually says. Get that consent in writing if
            you have not already.</li>
        <li>Do not assume platform delisting will arrive on day one of any new rule. Comply at the
            local licensing level first; the platform mechanism is the backstop, not the starting
            point.</li>
        <li>If you are in Selangor, plan your pricing and calendar as if a 180-night ceiling could
            apply from some date in 2026 or later, even though nothing is confirmed. It is easier to
            plan for a cap that never arrives than to unwind bookings for one that does.</li>
    </ul>

