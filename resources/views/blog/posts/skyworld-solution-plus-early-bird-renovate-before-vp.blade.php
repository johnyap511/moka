    <h2>What custom design means here</h2>
    <p>
        A package renovation gives every unit the same kitchen, the same wardrobe and the same
        feature wall. It is fast and it is cheap, and it looks like every other unit on the floor.
        Custom design takes the same floor plan and asks what this owner needs from it. A couple who
        cook every night get a kitchen planned around cooking. A family with two children gets
        storage in places a package never considers. A unit destined for short stays gets durable
        finishes, a layout that cleans fast, and a look that photographs well enough to book.
    </p>
    <p>
        The cost difference between a package and a considered custom design is smaller than most
        owners expect, because the expensive parts of a renovation, the wet works and the joinery,
        cost roughly the same either way. The difference is in the thinking, and that is what a
        design team is for.
    </p>

