    <p class="blog-lede">
        Seven stories from the past fortnight that matter if you own a short-stay unit in Malaysia:
        Singapore arrivals keep climbing, Formula 1 is back at Sepang in three weeks, Penang's licence
        deadline is six weeks away, and Selangor's 180-night cap is still a proposal. One line on each
        of what it means for you.
    </p>

    <h2>Singapore sent 10.74 million visitors in the first half</h2>
    <p>
        Bernama reported on 11 September that Malaysia recorded 10.74 million tourist arrivals from
        Singapore between January and June 2026, up 4.39% on the same period last year. Tourism Malaysia
        marked the number by launching the Rasa Malaysia 2026 food campaign in Singapore, running from
        11 September to 9 October at JEN Singapore Tanglin.
    </p>
    <p>
        <strong>For owners:</strong> Singapore remains the largest source market by a wide margin. If your
        unit is in Johor Bahru, Melaka or Kuala Lumpur, Friday and Saturday nights should be priced for
        Singaporean weekenders, and your listing should show the drive time or the Causeway crossing plainly.
    </p>

    <h2>Formula 1 at Sepang, 2 to 4 October</h2>
    <p>
        Formula 1 and the FIA confirmed in July that Sepang International Circuit will host the Bahrain
        Grand Prix on 2 to 4 October, the first Malaysian round since 2017, slotted between the Azerbaijan
        and Singapore races. The Star reported on 3 September that Trip.com saw hotel bookings around Sepang
        grow more than 1,600% and Traveloka saw Kuala Lumpur accommodation searches rise 7.9 times, with
        Indonesian travellers making up 71% of its flight bookings for the weekend.
    </p>
    <p>
        <strong>For owners:</strong> block any discounted or long-stay offers across 1 to 5 October now, set
        a three-night minimum, and price in steps rather than one jump. We have written a fuller plan in
        <a href="/blog/f1-sepang-2026-short-stay-pricing-guide">F1 is back at Sepang</a>.
    </p>

    <h2>The rest of the event calendar</h2>
    <p>
        The same report lists the second-half events pulling in visitors: BTS at Kuala Lumpur on 12 and
        13 December (more than 12,000 tickets sold on Trip.com's pre-sale day), the MotoGP round at Sepang,
        Evanescence and My Chemical Romance concerts, the Standard Chartered KL Marathon and the Penang
        Bridge International Marathon.
    </p>
    <p>
        <strong>For owners:</strong> event weekends are where a year's revenue gap opens or closes. Check
        that your calendar for those dates is not already sold at ordinary rates to a long booking.
    </p>

    <h2>Penang licences: applications close 1 November</h2>
    <p>
        Penang's Private Short-term Accommodation By-Laws 2026 came into force on 1 August, with a grace
        period to 1 November for operators to apply to MBPP or MBSP for a licence, Malay Mail reported on
        21 August. Residential-titled condominiums on the island cannot be licensed; serviced apartments
        and commercial-titled buildings can, with the building's consent.
    </p>
    <p>
        <strong>For owners:</strong> if your unit is in Penang and you have not started the building
        consent process, six weeks is tight. Our guide to the by-laws is
        <a href="/blog/penang-short-term-rental-rules-2026">here</a>.
    </p>

    <h2>Selangor's 180-night cap is still a proposal</h2>
    <p>
        Selangor announced last year that it intended to cap short-stay units at 180 nights a year from
        2026 and add a sustainability fee of RM2 a night for homestays and Airbnb units. As of this week we
        can find no gazetted by-law or council circular putting the cap into effect. The state said it
        would decide after studying the federal government's short-term accommodation guideline.
    </p>
    <p>
        <strong>For owners:</strong> nothing changes yet, but keep a record of nights booked per unit. If
        the cap arrives, the count will decide whether you need planning permission.
    </p>

    <h2>The national guideline is still in the pipeline</h2>
    <p>
        The Ministry of Housing and Local Government, through PLANMalaysia, has drafted a national
        Short-Term Residential Accommodation guideline meant to give every council the same rulebook.
        Property portals summarising the deputy tourism minister's remarks say it goes to Cabinet and then
        to the National Council for Local Government before states adopt it. No date has been given.
    </p>
    <p>
        <strong>For owners:</strong> until it lands, the rules are your state's and your building's.
        Penang has a law, Selangor has a proposal, Kuala Lumpur has DBKL's guidelines.
    </p>

    <h2>Around the region: Indonesia licences, Singapore stays closed, JB waits for the RTS Link</h2>
    <p>
        Indonesia's tourism ministry required every listing on Airbnb, Booking.com and Traveloka to hold a
        business licence by 31 March this year, and told the platforms to verify them; VnExpress reported
        the country expects up to 17 million visitors in 2026. Singapore still bars stays under three
        consecutive months in private homes. In Johor Bahru, AirDNA counts 7,765 active listings with
        occupancy of 43% and revenue up 16.1% year on year to June 2026, ahead of the RTS Link to Woodlands
        opening in 2027.
    </p>
    <p>
        <strong>For owners:</strong> the region is tightening rules while demand grows. Units that are
        licensed, insured and run by an accountable operator will keep the bookings the informal ones lose.
    </p>

