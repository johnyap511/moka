    <h2>Where the guests will stay</h2>
    <p>
        Sepang has few hotel rooms of its own, so the weekend spills outward. The circuit is next to KLIA,
        so units near the airport, in Cyberjaya and in Putrajaya are the closest short-stay stock. Kuala
        Lumpur city is about half an hour from the circuit by the KLIA Ekspres to KL Sentral and then the
        circuit shuttles, and it is where most visitors will want to be on the Friday and Sunday nights
        anyway. Serviced apartments in KLCC, Bukit Bintang and along the ERL line will fill first.
    </p>

    <h2>A pricing plan for 1 to 5 October</h2>
    <ol>
        <li><strong>Check your calendar today.</strong> If those dates are already sold at ordinary rates
            to a monthly or long booking, there is nothing to do but learn for MotoGP. If they are open,
            move on.</li>
        <li><strong>Turn off every discount</strong> for the window: weekly, monthly, last-minute, and any
            channel promotion that auto-applies.</li>
        <li><strong>Set a three-night minimum</strong> across Thursday 1 to Sunday 4 October. Two-night
            guests on Friday and Saturday leave Thursday and Sunday orphaned.</li>
        <li><strong>Raise the rate in steps, not one jump.</strong> Look at what comparable units within a
            kilometre are asking for the same nights, set yours just below the top of that band, and raise
            again when the first bookings land. A rate that is double your normal weekend is common for an
            event of this size; a rate that is four times it usually sits empty until the last day.</li>
        <li><strong>Write for the Indonesian guest.</strong> Say how far you are from the ERL or KLIA in
            minutes, mention the circuit shuttle, and state that you accept early check-in on race day
            if you can.</li>
        <li><strong>Hold the last unit.</strong> If you manage more than one unit in the same building,
            keep one back until the week before. Late demand for a sold-out event pays the most.</li>
    </ol>

