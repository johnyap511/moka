    <h2>What is confirmed</h2>
    <p>
        On 26 July, Formula 1 and the FIA announced that Sepang International Circuit will host the
        Bahrain Grand Prix on 2 to 4 October, after the original venue could not hold the race. It sits
        between the Azerbaijan round on 24 to 26 September and the Singapore Grand Prix on 9 to 11 October,
        which gives fans a two-race swing through Southeast Asia. The agreement is for 2026 only; whether
        Malaysia gets a permanent slot again depends on how this weekend goes.
    </p>

