    <h2>MotoGP returns to Sepang, 30 October to 1 November</h2>
    <p>
        Sepang International Circuit (SIC) said on 11 October that 80% of tickets for this year's
        Malaysian Motorcycle Grand Prix had already sold, with chief executive Azhan Shafriman Hanif
        targeting 200,000 spectators across the three days, above the 190,977 who attended in 2025.
        The race follows close behind the Formula 1 Gulf Air Bahrain Grand Prix, held at the same
        circuit on 2 to 4 October, which Bernama reported drew a record-breaking 261,000 spectators.
        SIC is holding parking rates at last year's level and will again allow motorcycles into the
        circuit grounds.
    </p>
    <p>
        <strong>For owners:</strong> two record-chasing crowds at Sepang inside a month is unusual
        demand. We have written a fuller pricing plan for the MotoGP weekend in
        <a href="/blog/motogp-sepang-2026-short-stay-pricing-guide">MotoGP is back at Sepang</a>.
    </p>

    <h2>Budget 2027: stamp duty relief and RM20 billion in housing guarantees</h2>
    <p>
        Tabling Budget 2027 on 9 October, Prime Minister Anwar Ibrahim proposed a full stamp duty
        exemption on first homes priced at RM500,000 and below, and a 50% reduction for first homes
        priced at RM750,000 and below, for sale and purchase agreements signed from 1 January 2027 to
        31 December 2030. A further RM20 billion was allocated to the Housing Credit Guarantee Scheme
        (SJKP), aimed at 80,000 first-time buyers, particularly the self-employed. Housing and Local
        Government Minister Nga Kor Ming called it "indeed a beneficial initiative, especially for
        young people who are planning to get married."
    </p>
    <p>
        <strong>For owners:</strong> if you are buying a unit to run as a short-stay property and it
        is your first home under RM750,000, it is worth timing the sale and purchase agreement for
        after 1 January 2027 to capture the exemption.
    </p>

    <h2>Tourism gets RM935 million in Budget 2027, up RM235 million</h2>
    <p>
        The Tourism, Arts and Culture Ministry's Budget 2027 allocation rose to RM935 million from just
        over RM700 million, The Star reported on 9 October. The money funds continued support for the
        Visit Malaysia campaign (extended into 2027), a matching grant for new direct flights from
        China, India, Central Asia and Europe, grants for industry players running tourism events, and
        a rise in the Ecological Fiscal Transfer ecotourism fund to RM270 million. The duty-free
        shopping limit in Langkawi and Labuan rises to RM10,000 for visitors staying at least 48 hours.
        Trip.com Malaysia general manager Stephane Thong welcomed the flight-route and event grants.
    </p>
    <p>
        <strong>For owners:</strong> new direct routes and a longer Visit Malaysia push mean more
        visitors over 2027, not a one-off bump; it is a reason to keep your listing and photos current
        rather than treat this as an event-only season.
    </p>

    <h2>Visit Malaysia 2026-2027 campaign reaches Vietnam and Indonesia</h2>
    <p>
        Tourism Malaysia ran trade engagements in Ho Chi Minh City on 14 October, led by director
        general Mohd Amirul Rizal Abdul Rahim, to grow arrivals from Vietnam, which sent 217,121
        visitors to Malaysia from January to August on 167 weekly flights. The same day, the agency's
        Jakarta office opened a business-to-business roadshow in Balikpapan, Manado and Denpasar,
        Bernama reported, its first promotional event in Manado since direct flights there stopped
        after the pandemic. Indonesia sent 4.3 million visitors to Malaysia in 2025 on more than 700
        weekly direct flights. Malaysia's 2026 target is 47 million international arrivals and RM329
        billion in tourism receipts.
    </p>
    <p>
        <strong>For owners:</strong> Vietnamese and Indonesian guests are a growing, not a niche,
        segment; listing photos and amenities that read well for family and group travel help here.
    </p>

    <h2>National short-term rental guideline: still short of the Cabinet</h2>
    <p>
        Responding to a written parliamentary question on 6 October, Housing and Local Government
        Minister Nga Kor Ming said the national Short-Term Rental Accommodation (STRA) planning
        guideline is at the "updating and final review stage" with the Tourism, Arts and Culture
        Ministry, and will go to the Cabinet before being tabled at the National Council for Local
        Government for agreement. Only after that would states and local authorities be asked to adopt
        it. Nga described the approach as "a national framework, with implementation based on the
        local context," covering premises registration, safety and cleanliness compliance, and operator
        accountability. No date was given for Cabinet consideration.
    </p>
    <p>
        <strong>For owners:</strong> nothing changes yet. Penang still has its own by-law (our guide is
        <a href="/blog/penang-short-term-rental-rules-2026">here</a>), and elsewhere your building's
        house rules and your local council remain the rules that apply; see
        <a href="/blog/working-with-building-management-and-authorities">working with your JMB and the
        council</a>.
    </p>

