@section('article')
    <p class="blog-lede">
        The months right after handover decide how quickly a new unit starts earning. Most of the
        delay owners experience is not renovation — it is paperwork, defect rectification and
        building permissions that could have been started earlier.
    </p>

    <h2>1. Inspect for defects before anything else</h2>
    <p>
        Your defect liability period is finite and it starts running at handover. Walk the unit
        properly, or pay someone to: check floor levels, door alignment, window seals, water
        pressure, drainage falls in the bathrooms, socket function, and every tile for hollowness.
    </p>
    <div class="blog-callout">
        <p>
            <strong>Log defects before you renovate, not after.</strong> Once you have tiled over,
            painted or installed built-ins, proving a defect was the developer's becomes difficult
            and rectification becomes yours to pay for. This is the most expensive ordering mistake
            in a new-unit setup.
        </p>
    </div>

    <h2>2. Confirm short stays are permitted — in writing</h2>
    <p>
        Ask the management office or JMB directly whether short-term letting is allowed, and
        whether a minimum stay applies. Read the by-laws yourself rather than relying on what an
        agent told you. Rules differ building to building, and enforcement has tightened in
        several areas.
    </p>
    <p>
        Ask specifically about: guest access cards, visitor registration, lift booking for
        move-ins, and whether the building charges for either.
    </p>

    <h2>3. Get the utilities live early</h2>
    <ul>
        <li><strong>Electricity and water</strong> — transferred into your name; some developments
            require a deposit.</li>
        <li><strong>Internet</strong> — the longest lead time of anything on this list. Some
            buildings have a single provider and a waiting list. Start it first.</li>
        <li><strong>Gas</strong> where applicable.</li>
    </ul>
    <p>
        Renovation needs power and water anyway, so there is no reason to delay these.
    </p>

    <h2>4. Sort access before your first guest</h2>
    <p>
        Access is where new hosts most often get caught out. Work out, in advance:
    </p>
    <ul>
        <li>How many access cards you can hold, and the replacement cost of a lost one.</li>
        <li>Whether guests can be registered at the guardhouse, and what the process is.</li>
        <li>Whether a lockbox or smart lock is permitted — many buildings have a view on this.</li>
        <li>Which lift guests use, and whether it needs card activation for your floor.</li>
    </ul>
    <p>
        A smooth self check-in at 1am is worth more to your reviews than most furnishing decisions.
    </p>

    <h2>5. Insurance</h2>
    <p>
        The building's master policy covers the structure, not your contents and not your
        liability to a guest. Tell your insurer the unit is let on short stays — a policy written
        for owner-occupation may not respond to a claim arising from paying guests. It is a short
        conversation and a bad one to have after an incident.
    </p>

    <h2>6. A realistic timeline</h2>
    <p>
        Assuming no major structural work, and depending heavily on your building's renovation
        rules:
    </p>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead><tr><th>Stage</th><th>Typically</th></tr></thead>
            <tbody>
                <tr><td>Defect inspection and rectification</td><td>Several weeks, developer-dependent</td></tr>
                <tr><td>Renovation approval and works</td><td>Weekday windows only in most buildings</td></tr>
                <tr><td>Furnishing and delivery</td><td>Lift bookings often required</td></tr>
                <tr><td>Photography and listing</td><td>A few days once styled</td></tr>
            </tbody>
        </table>
    </div>
    <p>
        The two items that most often blow the schedule are internet installation and lift booking
        availability. Both are free to start early, and neither depends on anything else being
        finished.
    </p>
@endsection
