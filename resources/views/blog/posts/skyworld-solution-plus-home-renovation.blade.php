    <h2>The order that saves you money</h2>
    <p>
        Doing these out of sequence is what turns a three-month renovation into a six-month one.
    </p>
    <ol>
        <li><strong>Defect inspection first.</strong> Log every defect during your defect liability
            period and get it rectified before renovation begins. Once you have tiled, painted or
            fitted built-ins, proving a defect was the developer's becomes difficult — and the cost
            of fixing it becomes yours.</li>
        <li><strong>Design before quoting.</strong> A contractor quoting from a finished design is
            quoting on the same scope as everyone else. A contractor quoting from a conversation is
            quoting on a guess, and variation orders follow.</li>
        <li><strong>Arrange financing early.</strong> MyDeco approval takes time. Start it before
            you commit to a schedule.</li>
        <li><strong>Book the renovation window.</strong> Most buildings restrict works to weekday
            working hours and require a deposit and permit from the management office.</li>
        <li><strong>Wet works before finishes.</strong> Anything involving plumbing, waterproofing
            or hacking happens before flooring, painting and joinery. Reversing this is expensive.</li>
        <li><strong>Furniture and styling last</strong>, with delivery slots booked — service lifts
            get busy in a newly handed-over building.</li>
    </ol>

