    <h2>Questions worth asking any renovator</h2>
    <ol>
        <li>Is the quotation itemised, and what specifically is excluded?</li>
        <li>Who applies for the renovation permit and pays the deposit?</li>
        <li>How are variations priced once work has started?</li>
        <li>What is the payment schedule, and what is tied to which milestone?</li>
        <li>Who supervises the site, and how often?</li>
        <li>What warranty covers the workmanship after handover?</li>
    </ol>
    <p>
