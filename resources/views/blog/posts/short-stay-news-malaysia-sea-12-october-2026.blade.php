    <h2>Budget 2027: RM935 million for tourism, Langkawi and Labuan duty-free raised to RM10,000</h2>
    <p>
        Prime Minister Anwar Ibrahim tabled Budget 2027 in the Dewan Rakyat on 9 October, allocating
        RM935 million for tourism and culture as the Visit Malaysia campaign is extended into 2027,
        Bernama reported. The duty-free shopping allowance in Langkawi and Labuan rises to RM10,000,
        conditional on a minimum 48-hour stay, and a new matching grant will help attract direct flight,
        cruise, ferry and tour-bus routes from China, India, Central Asia and Europe.
    </p>
    <p>
        <strong>For owners:</strong> if your unit is in Langkawi or Labuan, the 48-hour condition on the
        duty-free limit is a reason to push three-night minimums rather than one-night stays. We've set
        out the full budget breakdown for short-stay owners in
        <a href="/blog/budget-2027-what-short-stay-owners-need-to-know">our feature this week</a>.
    </p>

    <h2>Budget 2027: stamp duty exemption for first-time buyers extended to 2030</h2>
    <p>
        The same budget proposes a full stamp duty exemption on the loan agreement and transfer
        instrument for first homes up to RM500,000, and a 50% exemption on the portion between
        RM500,000 and RM750,000, for sale and purchase agreements signed from 1 January 2027 to
        31 December 2030, The Star reported on 9 October. A new RM20 billion Housing Credit Guarantee
        Scheme (SJKP) is meant to help 80,000 first-time buyers, including the self-employed, qualify
        for financing.
    </p>
    <p>
        <strong>For owners:</strong> if you are buying your first unit to run as a short-stay or monthly
        rental, the exemption window and the SJKP guarantee both apply only from 1 January 2027, so an
        SPA signed before year end does not qualify.
    </p>

    <h2>Haze returns: Johor and Negeri Sembilan hit hardest</h2>
    <p>
        Cross-border haze pushed 38 areas in Peninsular Malaysia into unhealthy API territory by
        8 October, Bernama reported, with Segamat in Johor recording the highest reading at 190,
        followed by Seremban and Nilai in Negeri Sembilan. The Department of Environment linked the
        smoke to 210 hotspots in Sumatra and 94 in Kalimantan, Indonesia, plus continuous dry weather.
        Readings had been lower but rising as of 5 October, when The Star reported 11 unhealthy areas
        with Batu Pahat and Larkin, both in Johor, the worst at 159.
    </p>
    <p>
        <strong>For owners:</strong> if your unit is in Johor or Negeri Sembilan, check your air
        purifier and have a message ready for guests on indoor alternatives; the National Haze Action
        Plan calls for outdoor activities to be suspended once API passes 100.
    </p>

    <h2>F1's Sepang weekend put RM345 million into local businesses</h2>
    <p>
        The Bahrain Grand Prix at Sepang on 2 to 4 October generated more than RM345 million in
        spillover for local micro, small and medium enterprises, Entrepreneur Development and
        Cooperatives Development Minister Steven Sim said in a Bernama report on 8 October. Almost
        half of the 261,000 spectators were foreign tourists, with the minister crediting hospitality,
        food and beverage, retail and transport.
    </p>
    <p>
        <strong>For owners:</strong> if you priced for the race weekend, compare what you earned
        against a normal weekend and keep the note for the next Sepang date; a one-off spike like this
        is exactly what minimum-stay and tiered pricing should be built around.
    </p>

