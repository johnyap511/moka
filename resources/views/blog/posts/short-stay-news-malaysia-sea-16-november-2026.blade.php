    <h2>Penang Island extends tourist-accommodation limits into George Town's heritage core</h2>
    <p>
        The Penang Island City Council (MBPP) will extend its tourist accommodation premises (TIP)
        rules into the George Town UNESCO World Heritage Site, state local government committee
        chairman Jason H'ng told the state Legislative Assembly on 3 November. The decision followed a
        28 September meeting between MBPP, PLANMalaysia and George Town World Heritage Incorporated,
        called after TIP operators complained about the rules introduced in August. Guidelines are
        still being drafted and will likely set a ratio or percentage of TIP premises allowed by zone,
        alongside the heritage site's existing land-use and building rules.
    </p>
    <p>
        <strong>For owners:</strong> if your unit sits inside the heritage core, the state by-law
        licence you may already hold will not be the last word. Watch for the zone-by-zone TIP ratio
        once PLANMalaysia finishes the guidelines; see our guides to
        <a href="/blog/penang-short-term-rental-rules-2026">Penang's 2026 by-laws</a> and
        <a href="/blog/penang-short-stay-fee-changes-2027">the 2027 fee changes</a> for what is already
        confirmed.
    </p>

    <h2>Thailand's weekly arrivals jump 18%, with Malaysia the single biggest source market</h2>
    <p>
        Thailand logged 636,432 foreign arrivals for 1 to 7 November, up 18.15% on the previous week,
        the Tourism and Sports Ministry reported on 9 November. Malaysia was the largest source market
        for the week with 79,693 visitors, up 28.87% on the same week last year, and ranks second for
        the year to date with 3,306,177 arrivals. Thailand's own year-to-date total of 26.1 million
        still sits 4.71% below the same period in 2025.
    </p>
    <p>
        <strong>For owners:</strong> Malaysians are travelling the region more, not less, even while
        Thailand's overall numbers lag last year. If you track exposure beyond your own unit, outbound
        Malaysian demand is a swing factor worth watching alongside your local occupancy.
    </p>

    <h2>Floods empty relief centres in Kuala Selangor and Hilir Perak</h2>
    <p>
        As of 11 November, 1,325 evacuees from 373 households remained at flood relief centres: 945
        people across five centres in Kuala Selangor, Selangor, and 380 across two centres in Hilir
        Perak (Teluk Intan and Langkap), The Star reported. Selangor's numbers had peaked at 3,798
        evacuees on 7 November before easing; Perak's flooding has largely subsided.
    </p>
    <p>
        <strong>For owners:</strong> Kuala Selangor and Hilir Perak are not short-stay hotspots, but the
        pattern is a familiar one each monsoon season. If any of your units sit in a flood-prone
        district, add a weather check and a guest-contact plan now, the way we already do for haze; see
        our <a href="/blog/southeast-asia-haze-2026-short-stay-hosting-guide">haze-season hosting
        guide</a> for the same approach applied to a different hazard.
    </p>

    <h2>Melaka pushes for 19 million visitors as the state goes into campaign mode</h2>
    <p>
        Melaka is targeting over 19 million tourist arrivals this year under Visit Melaka Year 2.0,
        with 225 tourism events planned and tourism revenue projected to reach RM20 billion, The Star
        reported on 12 November. Hotels remain the most popular paid accommodation for domestic
        visitors, with homestays and vacation homes the next most common choice. The state's own
        election campaign is under way, which local tourism players expect to bring extra visitors,
        media and candidates' supporters into the state.
    </p>
    <p>
        <strong>For owners:</strong> if you run a unit in Melaka, this is the state's biggest tourism
        push so far this year. Price for the campaign period and for the domestic, shopping-led crowd
        the state is chasing, rather than leaving your calendar on autopilot.
    </p>

    <h2>Sabah and the federal tourism ministry line up plans for Visit Sabah 2027</h2>
    <p>
        Sabah Chief Minister Hajiji Noor received a courtesy call from Deputy Tourism, Arts and Culture
        Minister Chiew Choon Man at Menara Kinabalu on 10 November, where both sides agreed to
        strengthen collaboration on integrated tourism promotion ahead of Visit Sabah Year 2027,
        Bernama reported. Sabah's campaign is being built around three themes: culture, adventure and
        nature.
    </p>
    <p>
        <strong>For owners:</strong> nothing here is a new rule, only coordination between Kota
        Kinabalu and Putrajaya on next year's marketing push. Still, a bigger promotion year is coming
        for Sabah; start thinking about your 2027 calendar pricing before the campaign materials do.
    </p>

