    <h2>The national short-stay guideline is finally close to Cabinet</h2>
    <p>
        Housing and Local Government Minister Nga Kor Ming told Parliament on 5 October that the national
        Short-Term Rental Accommodation (STRA) planning guideline is in its final review stage with the
        Tourism, Arts and Culture Ministry, and will then go to Cabinet. After that it goes to the National
        Council for Local Government for agreement, before states and local authorities are advised to adopt
        it. Nga said the guideline will focus on premises registration, safety and cleanliness compliance,
        and operator accountability, run as "a national framework, with implementation based on the local
        context." No date was given for Cabinet submission.
    </p>
    <p>
        <strong>For owners:</strong> this has been promised since 2019 and has slipped before, so treat
        "final review" as progress, not a deadline. Until it clears Cabinet and the states adopt it, your
        state's and your council's own rules still decide what you can do.
    </p>

    <h2>Budget 2027 puts RM935 million behind tourism</h2>
    <p>
        Budget 2027, tabled on 9 October, allocates RM935 million to the Tourism, Arts and Culture Ministry,
        up RM235 million on last year, to keep the extended Visit Malaysia campaign running through 2027. The
        Ecological Fiscal Transfer fund for community-based ecotourism rises to RM270 million. A new
        International and Charter Flight Matching Grant targets new direct routes from China, India, Central
        Asia and Europe. The duty-free shopping limit in Langkawi and Labuan rises to RM10,000 for visitors
        who stay at least 48 hours.
    </p>
    <p>
        <strong>For owners:</strong> the flight grant and the Langkawi duty-free rise point at two corridors
        worth watching for demand: Langkawi, and any city that gains a new direct route into KLIA or Penang.
    </p>

    <h2>Penang's licence deadline is days away</h2>
    <p>
        Penang's Private Short-term Accommodation By-Laws, in force since 1 August, give operators until
        1 November 2026 to apply for a TIP licence with MBPP or MBSP before enforcement begins. The industry
        side is still pushing back on cost: Jayden Lee, president of the Malaysia Short-Term Rental
        Accommodation Association (MySTRA), has called the roughly RM2,800-a-year minimum charge "far too
        high," and Lydia Tan of the Penang Malaysia Homestay/Short-Stay Operators Association says flat fees
        hit low-occupancy operators hardest.
    </p>
    <p>
        <strong>For owners:</strong> the fee argument is still open, but the deadline is not. We go through
        what to do before 1 November in this week's feature, below.
    </p>

    <h2>The RTS Link to Singapore slips to February</h2>
    <p>
        RTS Operations said on 2 October that passenger service on the Johor Bahru-Singapore RTS Link is now
        targeted for February 2027, with system tests and trial runs due to finish by 31 December 2026. The
        extra month is to allow time for independent safety certification and approvals from both countries'
        authorities; the previous target was 1 January 2027.
    </p>
    <p>
        <strong>For owners:</strong> a one-month slip this late in testing is normal for a cross-border rail
        project and not a sign of bigger trouble, but if you are pricing a Johor Bahru unit around the
        opening, push your "RTS Link opens" marketing to February 2027, not January.
    </p>

    <h2>Tourism Malaysia goes looking for Indonesian visitors beyond Jakarta</h2>
    <p>
        Tourism Malaysia ran a B2B roadshow in Balikpapan, Manado and Denpasar from 14 October under the
        Visit Malaysia 2026-2027 campaign, its first promotional event in Manado. Indonesia sent 4.3 million
        visitors to Malaysia in 2025 on more than 700 weekly direct flights, and the agency wants to revive
        the pre-pandemic Manado-Malaysia direct route. The national target stays at 47 million international
        arrivals and RM329 billion in tourism receipts for 2026.
    </p>
    <p>
        <strong>For owners:</strong> Indonesia is already Malaysia's second-largest source market after
        Singapore. A new Manado or Balikpapan route would feed Peninsular Malaysia gateways first, so it is
        worth watching rather than acting on yet.
    </p>

