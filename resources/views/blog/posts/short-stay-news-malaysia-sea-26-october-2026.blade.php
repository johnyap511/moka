    <p class="blog-lede">
        Five stories from the past week that matter if you own a short-stay unit in Malaysia: the national
        rulebook for short-term rentals is finally headed to Cabinet, Budget 2027 puts RM935 million behind
        tourism, Penang's licence deadline is days away, the RTS Link's opening date has moved again, and
        Tourism Malaysia is courting a new source market in Indonesia. One line on each of what it means
        for you.
