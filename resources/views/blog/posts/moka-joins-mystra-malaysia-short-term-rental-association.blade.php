    <p class="blog-lede">
        MOKA is now part of the community of the Malaysia Short-Term Rental Association, MySTRA. Here is
        what the association is, why we joined, and what it means for the owners whose units we manage.
    </p>

    <h2>What MySTRA is</h2>
    <p>
        MySTRA, the Malaysia Short-Term Rental Association, brings together operators, hosts and service
        companies in the short-stay sector. It is led by its president, Jayden Lee, and is one of the three
        industry bodies, alongside the Malaysian Vacation Rental association and the Malaysia Short Stay
        Hospitality Association, that support the STRA Forum and Expo, the sector's annual conference. The
        next edition is on 15 and 16 April 2027 at the KLGCC Convention Centre in Kuala Lumpur. The
        association's site is at <a href="https://mystra.org.my" rel="noopener" target="_blank">mystra.org.my</a>.
    </p>

    <h2>Why now</h2>
    <p>
        The rules for short stays in Malaysia are being written this year. Penang's by-laws came into force
        on 1 August. Selangor has proposed a 180-night cap. The Ministry of Housing and Local Government has
        drafted a national guideline that every council is expected to adopt. Decisions like these are made
        in meetings between the government and industry bodies, and an operator that is not in the room has
        no say in them.
    </p>
    <p>
        We manage units for owners across Kuala Lumpur, Selangor, Penang, Johor and Sabah. When a council
        changes a rule, it lands on our desk first and on our owners' statements second. Being inside the
        association means we hear about changes while they are still proposals, and we can put owners'
        concerns forward before they are settled.
    </p>

    <h2>What it means for our owners</h2>
    <ul>
        <li><strong>Earlier warning.</strong> Regulatory changes reach us through the association before
            they reach the news, and we pass them on in this blog and in owner updates.</li>
        <li><strong>A voice on your behalf.</strong> Owners rarely get consulted on short-stay rules. Through
            the association, the practical problems we see every day, from building consent to licence fees,
            are put to the people drafting them.</li>
        <li><strong>Standards you can point to.</strong> Buildings and councils increasingly ask who is
            running a unit. An operator that belongs to the national association, holds the licences and
            keeps the records is easier for a JMB to say yes to.</li>
    </ul>

    <div class="blog-callout">
        <p>
            If you own a unit and run it yourself, we would encourage you to look at the association too.
            The sector will be regulated either way; it is better regulated with hosts at the table.
        </p>
    </div>

    <h2>Where to find us</h2>
    <p>
        We will be at the STRA Forum and Expo in April 2027, and we take part in the association's
        discussions in between. If you are a developer, agent, building manager or owner who wants to talk
        about how the coming rules affect a building or a unit, get in touch.
    </p>

