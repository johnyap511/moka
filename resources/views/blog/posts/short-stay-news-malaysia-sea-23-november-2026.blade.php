    <h2>KPKT and MySTRA road-test the national STRA rulebook in Sepang</h2>
    <p>
        Deputy Housing and Local Government Minister Aiman Athirah Sabu launched a
        proof-of-concept pilot for short-term rental accommodation (STRA) in Sepang, Selangor, on
        6 November, run by PLANMalaysia with the Malaysia Private Accommodation Association
        (MySTRA) under the banner "Governing Fairly, Hosting Responsibly." Confined to Sepang
        Municipal Council's area, the pilot tests five things before the draft national
        guidelines reach Cabinet: whether the planning approach fits different sites, how
        registration and licensing should work, what operational standards apply, how data and
        digital platforms should be used, and what the draft guidelines still need fixing. KPKT
        was explicit that taking part is not automatic approval to operate and does not replace
        existing rules.
    </p>
    <p>
        <strong>For owners:</strong> nothing changes outside Sepang yet, but this is the clearest
        sign so far of what registration and licensing will actually look like once the national
        guidelines are adopted. We go through the pilot in detail, and what MySTRA membership
        means for us, in <a href="/blog/kpkt-stra-pilot-sepang-2026">our feature this week</a>.
    </p>

    <h2>Penang moves to bring George Town's heritage zone under its tourist-stay rules</h2>
    <p>
        Penang local government committee chairman Jason H'ng told the state assembly on 3
        November that MBPP, PLANMalaysia and George Town World Heritage Incorporated agreed at a
        28 September meeting to extend MBPP's tourist accommodation premises (TIP) rules to the
        George Town Unesco World Heritage Site, after operators inside the zone raised concerns
        once the wider by-law took effect in August. MBPP is still drafting the detail, including
        a permitted percentage of units, which will be added to the Special Area Plan it is
        preparing for the site.
    </p>
    <p>
        <strong>For owners:</strong> if your unit sits inside the heritage zone, treat this as a
        rules change coming rather than one already set; the ratio has not been fixed. See
        <a href="/blog/penang-short-stay-fee-changes-2027">our guide to Penang's fee changes</a>
        for the licence costs that already apply islandwide.
    </p>

    <h2>Singaporean buyers warm to Johor ahead of the RTS Link</h2>
    <p>
        Gerard Soosay, chairman of Rehda Malaysia's Johor branch, said on 18 November that he
        expects Singaporean demand for property in Johor Bahru and Iskandar Puteri to rise once
        the RTS Link opens, which he put at "next February." Interest has been building for two
        to three years, he said, but buyers are now more selective, weighing affordability against
        access to schools, healthcare and retail. He expects demand to concentrate near RTS Link
        stations once the line is running.
    </p>
    <p>
        <strong>For owners:</strong> Johor short-stay demand tied to the RTS Link is still a
        forecast, not a current surge; domestic buyers and tenants remain the core of the market
        for now.
    </p>

    <h2>Property investment approvals cool even as the wider economy grows</h2>
    <p>
        Mida recorded RM47.9 billion in real estate investment approvals for January to September
        2026, the second-largest services subsector, EdgeProp reported on 17 November. That is
        roughly 15.4% below the same period last year by EdgeProp's own calculation from Mida's
        rounded figures, even though total approved investment across the economy rose 20.7% to
        RM350.4 billion over the same months.
    </p>
    <p>
        <strong>For owners:</strong> if you're weighing a new purchase, this points to developers
        and institutional investors turning more selective on real estate specifically, not to
        the economy slowing generally.
    </p>

    <h2>Sabah leans on Putrajaya to promote Visit Sabah Year 2027</h2>
    <p>
        Sabah Chief Minister Hajiji Noor said on 10 November that the state is strengthening its
        collaboration with the Ministry of Tourism, Arts and Culture (MOTAC) to promote Sabah's
        destinations ahead of Visit Sabah Year 2027, after a courtesy call from Deputy Tourism
        Minister Chiew Choon Man and a MOTAC delegation. Hajiji said the campaign is meant to
        showcase local tourism products and give a boost to operators across the state.
    </p>
    <p>
        <strong>For owners:</strong> no dates or targets were announced yet; worth watching if you
        operate in Kota Kinabalu or elsewhere in Sabah, as campaign details should follow.
    </p>

