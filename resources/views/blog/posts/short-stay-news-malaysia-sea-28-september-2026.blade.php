    <h2>Malaysia's condo overhang keeps growing</h2>
    <p>
        The Real Estate and Housing Developers' Association (Rehda) released its Property Industry Survey
        for the first half of 2026 on 23 September: 59% of the 181 developers surveyed reported unsold
        completed units, and a third of those unsold units are priced at RM1 million and above. Sales still
        rose slightly, up 3.2% to 5,260 units, lifting the take-up rate to 33.2%.
    </p>
    <p>
        <strong>For owners:</strong> a soft resale and new-launch market is not the same as soft short-stay
        demand. We go through what the overhang actually changes for an owner in
        <a href="/blog/malaysia-condo-overhang-2026-owner-guide">our feature this week</a>.
    </p>

    <h2>F1 at Sepang is now bracketed by a second race in Singapore</h2>
    <p>
        Formula 1's Bahrain Grand Prix runs at Sepang on 2 to 4 October, with the Singapore Grand Prix
        following immediately on 9 to 11 October, Skift reported on 23 September. Amadeus booking data
        shows air arrivals from Kuala Lumpur to Singapore for 5 to 11 October tracking 74% higher year on
        year, Kuala Lumpur stays of one to five nights up 17%, and Singapore stays of six to 13 nights up
        49%, as fans combine both race weekends into a single trip.
    </p>
    <p>
        <strong>For owners:</strong> the demand window is wider than race weekend alone. If your unit is in
        KL, Putrajaya, Cyberjaya or near KLIA, keep rates elevated through the following week too, not just
        1 to 5 October — see our full pricing plan in
        <a href="/blog/f1-sepang-2026-short-stay-pricing-guide">F1 is back at Sepang</a>.
    </p>

    <h2>Sabah courts direct Beijing flights as Chinese arrivals climb</h2>
    <p>
        Sabah Tourism Minister Datuk Jafry Ariffin met China Eastern Airlines in Shanghai on 22 September,
        where the airline said it was looking to raise its Shanghai–Kota Kinabalu service to two or three
        daily flights and is exploring a new direct Beijing–Kota Kinabalu route, Malay Mail reported. Sabah
        welcomed 578,681 Chinese visitors between January and August 2026, up 21.6% on the same period last
        year.
    </p>
    <p>
        <strong>For owners:</strong> nothing is confirmed yet, but a direct Beijing route would open a
        second major Chinese gateway alongside Shanghai. Worth watching if you manage a unit in Kota
        Kinabalu ahead of Visit Sabah 2027.
    </p>

    <h2>Tourism Malaysia adds 118 new packages</h2>
    <p>
        Tourism Malaysia launched three new offerings on 23 September under Visit Malaysia 2026-2027: Edu+
        2.0 (29 packages for international students), EatVenture (23 gastronomy packages) and Taste of
        Orchard (66 agro-tourism packages built around durian, mangoes, cocoa and other farm produce),
        Bernama reported. Director-general Mohd Amirul Rizal Abdul Rahim said the aim is to diversify
        tourism products beyond the conventional ones.
    </p>
    <p>
        <strong>For owners:</strong> agro-tourism and food packages point visitors at smaller towns, not
        just KL and Penang. If your unit is near a farm-stay or food trail area, it is worth a line in your
        listing description.
    </p>

    <h2>Le Tour de Langkawi climbs two highland finishes back to back</h2>
    <p>
        The 30th edition of Le Tour de Langkawi started in Shah Alam on 27 September and runs to Putrajaya
        on 4 October, Bernama reported on 26 September. This year's route stays entirely on the peninsula's
        west coast, with a debut Cat.1 climb to Gunung Jerai in Kedah on 28 September, then Cameron
        Highlands on 30 September and Genting Highlands on 1 October — the first time the two highland
        finishes have run in consecutive stages since 2011.
    </p>
    <p>
        <strong>For owners:</strong> if your unit is near Taiping, Tanah Rata or Genting Highlands, expect a
        short bump in demand from teams, support crews and fans around each stage date.
    </p>

    <h2>Cambodia's arrivals nearly halve</h2>
    <p>
        Cambodia's Ministry of Tourism reported on 23 September that international arrivals fell 44.4% to
        2.25 million between January and August 2026, down from 4.05 million in the same period last year,
        VietnamPlus reported. The ministry cited the global economic slowdown, higher fuel prices and
        domestic challenges, and has offered Chinese passport holders a 14-day visa exemption from 15 June
        to 15 October to help. The Asian Development Bank has since cut its 2026 growth forecast for
        Cambodia to 3.9%, partly citing the tourism shortfall.
    </p>
    <p>
        <strong>For owners:</strong> it is a reminder that the region's recovery is uneven. Malaysia's
        arrivals growth this year looks considerably stronger by comparison, which is one reason regional
        platforms keep directing more listings and marketing budget here.
    </p>

