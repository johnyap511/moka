    <h2>What is confirmed</h2>
    <p>
        The Weeknd's After Hours Til Dawn tour added a second Kuala Lumpur date after the first
        presale sold out in about two hours; both 4 and 5 November shows at TM National Stadium,
        Bukit Jalil, sold out within two weeks. Ticket tiers averaged RM644.15 across eight price
        bands, and the stadium holds more than 80,000 people a night, so the two shows put well
        over 100,000 ticket-holders through Bukit Jalil in one weekend, before counting the
        friends, family and crew who travel with them.
    </p>

