    <p class="blog-lede">
        Penang gave short-stay operators a two-month grace period to apply for a TIP licence. That window
        closes on 1 November 2026. If your unit is in Penang and you have not applied yet, here is what the
        deadline actually means, what it costs, what the industry is still fighting over, and what to do
        before the date arrives.
    </p>

    <h2>What takes effect on 1 November</h2>
    <p>
        Penang's Private Short-term Accommodation By-Laws, which cover what the by-laws call a TIP (Tempat
        Inap Persendirian), came into force on 1 August 2026. Operators were given until 1 November to apply
        to MBPP or MBSP for a licence. From that date, both councils can act directly against operators
        without one: inspecting premises, investigating complaints and closing a unit down. We covered which
        properties can be licensed in the first place, and the building-consent step, in our full guide to
        the by-laws; this piece is about the deadline itself.
    </p>

    <h2>What a licence actually costs</h2>
    <p>
        The fee schedule has not changed since the by-laws were published in August, and it is the sticking
        point for the industry:
    </p>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead>
                <tr><th>Charge</th><th>Amount</th><th>When it's paid</th></tr>
            </thead>
            <tbody>
                <tr><td>Application fee</td><td>RM50</td><td>Once, with the application</td></tr>
                <tr><td>Annual licence (1 to 3 rooms)</td><td>RM1,000</td><td>Every year</td></tr>
                <tr><td>Extra room, up to 2 more</td><td>RM200 per room</td><td>Every year</td></tr>
                <tr><td>TIP accommodation fee</td><td>RM1,800 per unit</td><td>Every year</td></tr>
                <tr><td>Reminder notice on overdue fees</td><td>RM5</td><td>Per notice</td></tr>
            </tbody>
        </table>
    </div>
    <p>
        For a typical one- or two-bedroom unit, that is about RM2,850 in the first year and RM2,800 every
        year after. On a unit earning RM5,000 a month that is roughly five percent of annual revenue; on a
        unit earning RM2,000 a month it is closer to twelve percent.
    </p>

    <p>
        A five-bedroom unit, the largest size the fee table covers, adds RM400 for its two extra rooms on
        top of the RM1,000 base licence, so the annual licence alone rises to RM1,400. Add the RM1,800 TIP
        fee and the RM50 one-off application fee, and a larger unit's first-year bill runs to roughly
        RM3,250, against RM2,850 for a typical one- to three-bedroom unit.
    </p>

    <h2>Why operators are still pushing back</h2>
    <p>
        The fee has drawn consistent criticism since it was published. Jayden Lee, president of the Malaysia
        Short-Term Rental Accommodation Association (MySTRA), says "a minimum annual charge of RM2,800 per
        unit is far too high," and has asked for tiered fees by unit count, lower rates for small operators,
        and a longer rollout with compliance support before penalties start. Lydia Tan, chairman of the
        Penang Malaysia Homestay/Short-Stay Operators Association, makes a similar point from the small-host
        side: the fee is flat regardless of occupancy, and some of her members get fewer than five bookings a
        month. Both associations support licensing in principle; neither has reported a change to the fee or
        the deadline. Confirm the current fee schedule with MBPP or MBSP directly before you apply, as neither
        council has publicly committed to revising it.
    </p>
    <div class="blog-callout">
        <p>
            We think the fee argument and the deadline are two different questions. The deadline is set; the
            fee may still move. Apply on time and keep the receipt, whatever happens to the schedule later.
        </p>
    </div>

    <h2>What happens if you miss it</h2>
    <p>
        After 1 November, MBPP and MBSP gain the power to inspect, investigate and close down unlicensed
        TIP operations directly, rather than only acting through the building. Both councils cite a backlog
        of complaints as the reason for the by-laws in the first place: MBPP logged 364 nuisance and safety
        complaints tied to unlicensed short-term units between 2020 and March 2026, and MBSP another 24.
        Running a unit unlicensed after the deadline is not a quiet option; it is the exact behaviour the
        by-laws were written to stop.
    </p>

    <h2>What to do now</h2>
    <ol>
        <li>Check your title. Residential-titled strata on Penang Island cannot be licensed at all,
            whatever the building's house rules say; our full by-laws guide has the table.</li>
        <li>If your unit can be licensed, confirm your building's management body (JMB or MC) has approved
            short-term rentals by special resolution. No consent, no licence.</li>
        <li>Gather the paperwork: title or sale and purchase agreement, the management body's consent,
            company registration if you operate through one, and the floor plan for the room count.</li>
        <li>Apply to MBPP or MBSP before 1 November 2026, and keep proof of the application date.</li>
        <li>If your unit cannot be licensed, or the numbers no longer work once you add the annual fee,
            switch it to a monthly furnished tenancy rather than keep operating and wait for a complaint.</li>
    </ol>
