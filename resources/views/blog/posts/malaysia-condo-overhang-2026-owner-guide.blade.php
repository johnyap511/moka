    <p class="blog-lede">
        Rehda's latest survey of Peninsular Malaysia developers puts a hard number on something owners can
        already feel: a lot of completed condo units are sitting empty. Fifty-nine percent of developers
        surveyed reported unsold completed stock in the first half of 2026. That is a developer problem
        first, but it changes the maths for anyone who owns, or is about to collect, a unit that is not
        yet earning.
    </p>

    <h2>What the survey found</h2>
    <p>
        The Rehda Institute surveyed 181 Rehda members across Peninsular Malaysia in July and August 2026,
        covering performance in the first half of the year. Fifty-four developers launched 15,834 new
        units, almost flat on the 15,841 launched in the second half of 2025, with 53% of those launches
        priced between RM300,001 and RM500,000. Sales still edged up: 5,260 units changed hands, 3.2% more
        than the 5,098 sold in the second half of 2025, lifting the take-up rate from 32.2% to 33.2%.
        Apartments and condominiums were the best-selling type, accounting for 3,032 of those sales.
    </p>
    <p>
        The overhang sits alongside that modest growth. Fifty-nine percent of developers reported unsold
        completed units, and a third of those unsold units are priced at RM1 million or more. Rehda
        president Datuk Zaini Yusoff pointed to a wider point behind the numbers: housing affordability is
        not just about the sale price, but also "the cost of producing and delivering housing."
    </p>

    <h2>Why units are going unsold</h2>
    <p>
        The survey traces most of the unsold stock to three things: buyers being rejected for financing,
        prices that have moved ahead of what buyers can borrow, and Bumiputera-quota units that developers
        have not yet been able to release to the open market. On the financing side, the rejections trace
        back to buyers' income eligibility, lower financing margins from banks, and adverse credit
        histories, not a lack of buyer interest in the units themselves.
    </p>
    <p>
        That distinction matters for an owner. A unit can be hard to sell for reasons that have nothing to
        do with whether it is a good place to stay. A bank's view of a buyer's income has no bearing on
        whether a guest wants to book the same unit for a weekend.
    </p>

    <h2>What this changes if you already own a unit</h2>
    <p>
        An overhang does not lower your unit's nightly rate. It changes the calculation around holding,
        selling or converting a unit that is not currently earning. The table below is how we would think
        through it depending on why the unit was bought.
    </p>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead>
                <tr><th>Why you hold the unit</th><th>What the overhang means for you</th></tr>
            </thead>
            <tbody>
                <tr><td>Bought to sell on completion</td><td>A crowded resale market with more competing listings makes a quick flip harder. Renting it out, short-stay or long-term, buys time without the unit sitting empty.</td></tr>
                <tr><td>Bought as a long-term investment</td><td>Soft resale prices do not change rental yield. If the unit suits short-stay, occupancy and nightly rate matter more than what the unit could sell for this year.</td></tr>
