    <h2>What to do now</h2>
    <ul>
        <li>If your unit is unsold or newly handed over, work out the monthly cost of it sitting empty
            (maintenance, quit rent, loan servicing) before deciding to wait out the market.</li>
        <li>Check your building's title type and JMB or MC consent status before assuming you can list it
            short-stay.</li>
        <li>If you are shopping for a unit in a building with known unsold stock, ask the developer about
            furnishing packages or price flexibility before you negotiate.</li>
        <li>Do not treat a soft resale price as a signal about rental demand; they are driven by different
            things.</li>
    </ul>

