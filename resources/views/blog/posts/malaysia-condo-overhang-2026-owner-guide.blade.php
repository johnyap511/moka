                <tr><td>Considering buying into the overhang</td><td>Developers with unsold completed stock are often more open to negotiating on price, furnishing packages or early handover. Check the building's short-stay standing before you commit.</td></tr>
            </tbody>
        </table>
    </div>

    <h2>Short-stay is one way out of an empty unit, not the only one</h2>
    <p>
        Converting an unsold or newly-completed unit to short-stay only works if the building allows it. A
        residential-titled unit in Penang cannot be licensed at all under the island's new by-laws; in most
        other states the building's JMB or MC has to consent before you can list a unit on any nightly
        platform. We cover the consent process in
        <a href="/blog/working-with-building-management-and-authorities">working with your JMB and the
        council</a>, and Penang's specific rules in
        <a href="/blog/penang-short-term-rental-rules-2026">our guide to the by-laws</a>. Check where your
        building and title stand before assuming short-stay is available to you.
    </p>
    <p>
        Where it is allowed, short-stay has one advantage a stagnant resale listing does not: it produces
        cash flow while you wait for the wider market, and for developer sentiment, to improve. Rehda's own
        survey points to loan rejections easing only if financing conditions change, which is outside any
        single owner's control.
    </p>

