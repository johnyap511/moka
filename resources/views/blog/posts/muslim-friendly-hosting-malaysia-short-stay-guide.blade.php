    <p class="blog-lede">
        Malaysia has just held onto the top spot in the Global Muslim Travel Index for an eleventh
        year running, and this month's Islamic Tourism Month is putting that ranking in front of
        travellers directly. None of it requires a licence or a certificate for a short-stay owner.
        Here is what the ranking is built on, what it actually means for a booking, and what is worth
        adding to your unit.
    </p>

    <h2>Malaysia is still the world's No. 1</h2>
    <p>
        The Mastercard-CrescentRating Global Muslim Travel Index (GMTI) 2026 kept Malaysia as the top
        Muslim-friendly destination for the eleventh consecutive year, Bernama reported on 12
        September. The government's Islamic Tourism Centre, under the Ministry of Tourism, Arts and
        Culture, is running the fifth edition of Islamic Tourism Month this month to put that ranking
        in front of both domestic and international travellers, promoting Muslim-friendly
        destinations, accommodation and products nationwide.
    </p>

    <h2>What "Muslim-friendly" means for a booking, not a building</h2>
    <p>
        There is no such thing as a "halal-certified condo," and guests looking for a short-stay unit
        are not expecting one. The certification schemes Malaysia runs for this market are aimed at
        registered businesses: the Islamic Tourism Centre's Muslim-Friendly Tourism and Hospitality
        Assurance and Recognition (MFAR) programme recognises hotels and other tourist accommodation
        premises, alongside spas and travel operators, for meeting Muslim-friendly guidelines. A
        privately let condo unit is not the kind of premise MFAR is built to assess. What a Muslim
        traveller actually notices when they walk into your unit is simpler than a certificate, and
        it costs little to get right.
    </p>

    <h2>What the official guidance points to</h2>
    <p>
        The Islamic Tourism Centre's own description of MFAR-recognised hotels lists the amenities it
        checks for: halal food options, cleanliness, appropriate toiletries, and prayer spaces that
        face the qibla. That is a reasonable list for any short-stay unit to borrow from, scaled down
        to what a single condo can actually offer.
    </p>

