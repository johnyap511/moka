    <h2>What to do now</h2>
    <ul>
        <li>Add a prayer mat and a qibla marker if your unit does not have one; both are cheap and take five minutes.</li>
        <li>Write a one-line kitchen note on what is stocked, and keep any alcohol out of the default welcome basket.</li>
        <li>List the nearest surau and a halal eatery or two in your house rules or welcome message.</li>
        <li>Do not claim a certification you do not hold; let the amenities speak for themselves.</li>
        <li>Mention Islamic Tourism Month in your listing description while it is current this month.</li>
    </ul>

