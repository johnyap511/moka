    <h2>Where to be careful</h2>
    <p>
        Do not describe your listing as "halal-certified" or "MFAR-certified" if you have not gone
        through the scheme yourself; it is not a label to borrow. Muslim travellers are not one
        market either: guests from the Gulf, from Indonesia and from Malaysia's own domestic market
        arrive with different expectations, and some will not use any of the additions above. Treat
        the list as a low-cost default that removes friction for the guest who does want it, not a
        theme to redecorate around.
    </p>
    <p>
        It is also worth checking what your building already provides. Most Malaysian condominiums
        already have a surau on the compound; a line in your house rules pointing guests to it is
        often more useful than anything you put inside the unit.
    </p>

