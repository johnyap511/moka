    <p class="blog-lede">
        Penang's short-stay licence just got cheaper, five months after the state introduced it.
        Amendments to the Private Short-term Accommodation By-Laws 2026, confirmed on 3 November
        and taking effect 1 January 2027, halve the annual licence fee and replace a flat
        accommodation fee with a scale tied to room count. Here is exactly what changes, what
        does not, and what we think owners should still watch.
    </p>

    <h2>What changes on 1 January 2027</h2>
    <p>
        When the by-laws first took effect on 1 August 2026, a typical unit faced a RM50
        application fee, an annual licence fee from RM1,000 for up to three rooms, and a flat
        RM1,800 a year accommodation (TIP) fee per unit, roughly RM2,850 a year in council
        charges for a two-bedroom unit before anything else. The amendment keeps the application
        fee but cuts the licence fee to RM500 for units with up to three rooms, with extra rooms
        still costing more. It also drops the flat TIP fee for a tiered scale, so a studio or
        one-bedroom unit pays far less than a five-room villa.
    </p>
    <p>
        Penang's local government committee chairman H'ng Mooi Lye said the changes follow
        feedback from operators, industry associations and NGOs, and are meant to make
        compliance more affordable now that enforcement has started.
    </p>

    <h2>The new fee table</h2>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead>
                <tr><th>Rooms</th><th>TIP fee from 1 Jan 2027</th><th>TIP fee before</th></tr>
            </thead>
            <tbody>
                <tr><td>1 room</td><td>RM400</td><td>RM1,800 (flat, all unit sizes)</td></tr>
                <tr><td>2 rooms</td><td>RM600</td><td>RM1,800</td></tr>
                <tr><td>3 rooms</td><td>RM800</td><td>RM1,800</td></tr>
                <tr><td>4 rooms</td><td>RM1,000</td><td>RM1,800</td></tr>
                <tr><td>5 to 10 rooms</td><td>RM1,800</td><td>RM1,800</td></tr>
            </tbody>
        </table>
    </div>
    <p>
        The annual licence fee drops from RM1,000 to RM500 for up to three rooms on top of this.
        A one-bedroom unit's council charges fall from roughly RM2,850 a year to around RM950, a
        meaningful difference if your unit earns closer to RM2,000 than RM5,000 a month. Larger
        units, five rooms and up, see no change to the TIP fee and should confirm the exact
        licence-fee add-on for extra rooms with MBPP or MBSP directly, as the published amendment
        did not give a per-room figure.
    </p>

    <h2>Why Penang moved to cut fees so soon</h2>
    <p>
        The by-laws were barely three months old when the state revised them, which says
        something about the pushback it received. Lydia Tan, chairman of the Penang Malaysia
        Homestay/Short-Stay Operators Association, said at the 3 November press conference that
        compliant operators want to be recognised as legitimate stakeholders and welcomed the
        lower fees as a step toward that. We think the quick revision is a reasonable sign that
        the state is still listening, which matters if you plan to raise your own case for an
        exception or a correction later.
    </p>

    <h2>What the amendment does not change</h2>
    <p>
        The licensing map itself is untouched. MBPP still bars short-term rental in all stratified
        residential buildings on the island; MBSP still allows it in residential and commercial
        areas on the mainland. The two-month grace period to register, which ran from 1 August to
        1 November 2026, has already closed, and H'ng warned that non-compliant operators still
        face a compound of up to RM1,000, up to a year in jail, or seizure of the premises. The
        amendment also clarifies the line between a TIP and a hotel, based on actual use rather
        than branding, specifically to stop hotel operators relabelling rooms as private lodgings
        to dodge hotel licensing standards. If you own a unit on a residential title on the
        island, none of this changes your position; see
        <a href="/blog/penang-short-term-rental-rules-2026">our original guide to the by-laws</a>
        for which titles and building types can be licensed at all.
    </p>
    <p>
        One new concession: landed property owners under MBPP now get a three-year grace period
        before planning-permission requirements for changing residential use to commercial apply,
        though they still need their neighbours' sign-off before the council will consider an
        application.
    </p>

    <h2>The single-licence request is not yet granted</h2>
    <p>
        Operators with several units asked for one licence to cover up to ten of them, which
        would simplify paperwork and cut compliance costs for anyone running a small portfolio.
        The state has not agreed to this. Until it does, assume you still need a separate licence
        and a separate TIP fee for every unit you operate in Penang, and plan your renewal
        paperwork on that basis.
    </p>

