    <h2>What to do now</h2>
    <ul>
        <li>If you already hold a Penang TIP licence, check your renewal notice against the new
            fee table above rather than assuming the old schedule still applies.</li>
        <li>If you missed the 1 November grace period, apply now. The lower fees do not change
            the penalties for operating without a licence.</li>
        <li>If you own more than one unit, budget for a separate licence and TIP fee per unit
            until the single-licence request is decided.</li>
        <li>If you own landed property under MBPP, use the three-year planning-permission window
            to get your neighbours' sign-off rather than leaving it to the last year.</li>
    </ul>

