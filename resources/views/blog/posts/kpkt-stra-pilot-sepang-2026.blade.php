    <p class="blog-lede">
        On 6 November, Deputy Housing and Local Government Minister Aiman Athirah Sabu launched a
        proof-of-concept pilot for short-term rental accommodation (STRA) in Sepang, Selangor. It
        is the first time the draft national rulebook, still months from Cabinet, has been tested
        against a real local authority. Here is what the pilot actually covers, who is running
        it, and what it changes for owners right now.
    </p>

    <h2>What happened in Sepang</h2>
    <p>
        The pilot is run by PLANMalaysia, the federal town planning department under KPKT,
        together with the Malaysia Private Accommodation Association (MySTRA), under the banner
        "Governing Fairly, Hosting Responsibly." It applies only within Sepang Municipal
        Council's area. KPKT was explicit about the limits: taking part is not automatic approval
        to operate, and it does not replace any existing regulatory mechanism. Nothing about it
        changes the rules for a short-stay unit anywhere else in Malaysia today.
    </p>
    <p>
        The timing matters. On 26 October, Deputy Minister Aiman Athirah told the Dewan Rakyat
        that the national STRA planning guidelines were in their final review stage with the
        Ministry of Tourism, Arts and Culture (Motac), ahead of Cabinet consideration and then the
        National Council for Local Government. Sepang is where that draft meets an actual
        council, before it is locked in for the rest of the country.
    </p>

    <h2>The five things the pilot is testing</h2>
    <p>
        PLANMalaysia set out five areas the Sepang pilot is meant to work through. None of them
        are final; all are meant to be refined before the national guidelines go to Cabinet.
    </p>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead>
                <tr><th>Area</th><th>What it covers</th></tr>
            </thead>
            <tbody>
                <tr><td>Planning fit</td><td>Whether the planning approach suits different sites: land use, environmental factors, property characteristics</td></tr>
                <tr><td>Registration and licensing</td><td>How the application and licensing process should work, and how agencies coordinate it</td></tr>
                <tr><td>Operational standards</td><td>Safety, cleanliness, guest management, shared facilities and handling of community complaints</td></tr>
                <tr><td>Data and platforms</td><td>How registration, monitoring and information are coordinated digitally</td></tr>
                <tr><td>Guideline drafting</td><td>Refining the draft planning guidelines, local authority procedures and related policy</td></tr>
            </tbody>
        </table>
    </div>
    <p>
        Read in order, the list is a fair description of what has been missing from Malaysia's
        short-stay regulation so far: a single, tested process for registering and licensing a
        unit, consistent operational standards, and a digital way for local authorities and
        platforms to check who is actually licensed.
    </p>

    <h2>Why MySTRA is in the room</h2>
    <p>
        MySTRA's involvement is notable because it is an industry association, not a regulator.
        We joined MySTRA in September, as we
        <a href="/blog/moka-joins-mystra-malaysia-short-term-rental-association">wrote at the
        time</a>, because the national rules were still being written and we wanted a seat in
        that process rather than finding out the outcome afterwards. Having MySTRA co-run the
        pilot, rather than only government agencies, means an association that represents working
        operators is shaping the registration and compliance process KPKT is testing, not just
        reacting to it once published.
    </p>

    <div class="blog-callout">
        <p>
            We think a pilot confined to one council, with an industry association at the table,
            is a more useful signal than another ministerial statement about guidelines being
            "finalised." It tells us what registration and compliance will actually require to
            operate, not just that rules are coming.
        </p>
    </div>

    <h2>What the pilot does not change</h2>
    <p>
        Outside Sepang, your position is exactly what it was before 6 November. Strata buildings
        are still governed by their JMB or MC under the Strata Management Act 2013. The 180-night
        annual cap floated in October is still only proposed, with no decision date attached. The
        national guidelines still have to clear the Cabinet and then the National Council for
        Local Government before states and councils adopt them, a process Aiman Athirah has not
        put a date on.
    </p>

    <h2>Where this fits in the bigger STRA timeline</h2>
    <p>
        Malaysia's short-stay rules have moved in two tracks this year: states and councils
        setting their own licensing, and the federal guideline working toward a single national
        standard. Penang has been the test case for the first track, with its by-laws in force
        since 1 August and its fees revised from 1 January 2027. The Sepang pilot is the clearest
        move yet on the second track: a live rehearsal of what the federal standard will ask
        local authorities, platforms and operators to do once it is adopted.
    </p>

    <h2>What to do now</h2>
    <ul>
        <li>If you operate in Sepang, expect the council and MySTRA to be more visible on
            registration and compliance over the coming months; taking part is not compulsory and
            carries no penalty for sitting it out.</li>
        <li>Everywhere else, no new paperwork or fee applies yet. Keep whatever local licence or
            strata consent you already need in Penang, Kuala Lumpur or your own council area in
            order, since the direction of travel is toward stricter registration, not looser.</li>
        <li>Watch for the guidelines reaching Cabinet, then the National Council for Local
            Government; that is the point the Sepang pilot's findings would translate into rules
            for the rest of the country.</li>
        <li>If you list on a platform, expect platforms to eventually be asked to check licence
            status before listing a property, which is already part of the draft framework KPKT
            described in October.</li>
    </ul>

