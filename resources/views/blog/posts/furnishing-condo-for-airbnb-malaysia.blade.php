@section('article')
    <p class="blog-lede">
        Furnishing budgets get spent in the wrong places more often than they get spent too
        thinly. Guests barely register the feature wall. They register the mattress, the
        air-conditioning and whether the wifi holds a video call — and those are what the reviews
        are about.
    </p>

    <h2>Spend heavily on sleep</h2>
    <p>
        More short-stay reviews turn on sleep quality than on anything else. Four things carry
        almost all of it:
    </p>
    <ul>
        <li><strong>The mattress.</strong> The one item worth buying above your instinct. A cheap
            mattress generates bad reviews for years and cannot be disguised.</li>
        <li><strong>Blackout curtains.</strong> Not "thick" curtains — genuine blackout. Malaysian
            mornings are bright early, and guests on holiday sleep late.</li>
        <li><strong>Air-conditioning that works quietly.</strong> Service it on a schedule. A noisy
            or weak unit ruins the night and is the single most common maintenance complaint.</li>
        <li><strong>Sound.</strong> Soft furnishings, rugs and door seals reduce corridor and
            traffic noise more cheaply than anything structural.</li>
    </ul>

    <h2>Then the things guests use constantly</h2>
    <ul>
        <li><strong>Wifi.</strong> Many guests are working. Pay for a proper plan and put the
            router where the signal reaches the bedrooms.</li>
        <li><strong>Hot water.</strong> Check pressure and recovery time with the shower actually
            running, not by looking at the heater.</li>
        <li><strong>Power outlets by the bed.</strong> On both sides. Add USB points.</li>
        <li><strong>Lighting in layers.</strong> Overhead plus bedside plus something warm in the
            living area. Single-source lighting photographs badly and feels institutional.</li>
        <li><strong>Somewhere to put a suitcase.</strong> Open floor space or a luggage rack.
            Guests live out of their bags.</li>
    </ul>

    <h2>Buy for durability, not for a showroom</h2>
    <p>
        Everything will be used by people who did not pay for it and will not be back. That is not
        cynicism, just the operating condition.
    </p>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead><tr><th>Avoid</th><th>Prefer</th><th>Why</th></tr></thead>
            <tbody>
                <tr><td>Light fabric sofas</td><td>Darker, tight-weave or leatherette</td><td>Stains are permanent and visible in photos</td></tr>
                <tr><td>Glass table tops</td><td>Solid or laminate</td><td>Chips, smears, breakage risk</td></tr>
                <tr><td>White grout</td><td>Mid-tone grout</td><td>Discolours quickly under heavy use</td></tr>
                <tr><td>High-gloss white cabinets</td><td>Matt or textured finishes</td><td>Every fingerprint shows</td></tr>
                <tr><td>Deep-pile rugs</td><td>Flat-weave, washable</td><td>Cannot be cleaned between same-day turnovers</td></tr>
            </tbody>
        </table>
    </div>

    <h2>Buy in threes</h2>
    <div class="blog-callout">
        <p>
            Keep three sets of linen and towels per bed and bathroom: one on the bed, one in the
            cupboard, one in the wash. Two sets fails the moment you get a same-day turnover, and
            same-day turnovers are exactly the days you are earning most.
        </p>
    </div>

    <h2>Details that cost little and get mentioned</h2>
    <ul>
        <li>A full-length mirror.</li>
        <li>Enough hangers — a dozen, not four.</li>
        <li>A kettle, and mugs that match.</li>
        <li>Basic cooking equipment that is actually usable: a sharp knife, a pan that is not warped.</li>
        <li>A simple welcome note with the wifi password, bin day and the lift access rules.</li>
        <li>A nightlight or dim switch for guests navigating an unfamiliar unit at 3am.</li>
    </ul>

    <h2>Photograph it properly, once</h2>
    <p>
        Furnishing decides the guest experience; photography decides whether anyone books in the
        first place. Shoot in daylight, with every light on, after a full clean and with all
        clutter removed. This is the one part of the process where paying a professional reliably
        pays for itself — your photos compete against every other listing in the building.
    </p>
    <p>
        Then re-shoot when you change something meaningful. Listings quietly decay as the photos
        stop matching the unit.
    </p>
@endsection
