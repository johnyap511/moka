    <p class="blog-lede">
        Handing your condo to a short-stay management company is a bigger decision than most
        owners expect. You are not just outsourcing cleaning — you are handing over pricing,
        guest selection and the reviews your listing lives or dies by. Here is what the
        arrangement actually involves, and what to ask before you sign anything.
    </p>

    <h2>What a management company actually does</h2>
    <p>
        The visible part is housekeeping and guest messaging. The part that decides your
        earnings is less visible:
    </p>
    <ul>
        <li><strong>Listing and distribution.</strong> Creating the listing, writing it properly,
            and publishing across several platforms rather than Airbnb alone. A unit on three
            platforms sees far more demand than one on a single channel.</li>
        <li><strong>Photography.</strong> The single biggest lever on click-through rate. Phone
            photos in poor light will cost you bookings no amount of pricing can recover.</li>
        <li><strong>Price optimisation.</strong> Rates that move with weekday and weekend demand,
            school holidays, concerts and conferences. Static pricing is the most common reason a
            well-located unit underperforms.</li>
        <li><strong>Guest vetting.</strong> Screening enquiries and declining the bookings most
            likely to result in a party, a complaint from the building, or damage.</li>
        <li><strong>Turnovers.</strong> Cleaning, linen, restocking and inspection between stays,
            reliably and on a same-day schedule when back-to-back bookings occur.</li>
        <li><strong>Maintenance response.</strong> Someone who can be on site when the air-con
            fails at 9pm, because a guest without air-con becomes a one-star review by morning.</li>
    </ul>

    <h2>How fees are usually structured</h2>
    <p>
        Most Malaysian managers charge a percentage of the revenue they generate, which aligns
        their incentives with yours — they earn more only when you do. Some charge a flat monthly
        fee regardless of performance; be careful with that structure, because it pays the same
        whether your unit is full or empty.
    </p>
    <p>
        Percentages vary by operator, by city and by how much work the unit needs, so treat any
        single published number with suspicion. What matters more than the headline rate is what
        sits inside it.
    </p>

    <h3>Ask exactly what the percentage covers</h3>
    <div class="blog-table-wrap">
        <table class="blog-table">
            <thead>
                <tr><th>Item</th><th>What to confirm</th></tr>
            </thead>
            <tbody>
                <tr><td>Cleaning</td><td>Charged to the guest, to you, or absorbed in the fee?</td></tr>
                <tr><td>Linen and consumables</td><td>Who buys and replaces them, and how often?</td></tr>
                <tr><td>Photography</td><td>One-off charge, or included at onboarding?</td></tr>
                <tr><td>Maintenance</td><td>Is there a limit below which they act without asking you?</td></tr>
                <tr><td>Platform fees</td><td>Quoted on gross or net revenue?</td></tr>
                <tr><td>Exit</td><td>Notice period, and who keeps the listing and its reviews?</td></tr>
            </tbody>
        </table>
    </div>
    <p>
        That last row matters more than owners realise. A listing's review history is an asset.
        If your manager holds the account, leaving may mean starting from zero reviews.
    </p>

    <h2>Check your building allows it — first</h2>
    <div class="blog-callout">
        <p>
            <strong>Do this before anything else.</strong> Short-stay letting in Malaysia is
            governed by a mix of local council rules and, crucially, your building's own by-laws.
            Some managements permit it, some restrict minimum stays, and some prohibit it outright.
            Check with your JMB or MC and your local council <em>before</em> you spend on
            furnishing. Owners who skip this step sometimes finish a renovation only to find they
            cannot legally host.
        </p>
    </div>

    <h2>Questions worth asking before you sign</h2>
    <ol>
        <li>How many units do you currently manage, and how many are in my building or area?</li>
        <li>What occupancy and average nightly rate are comparable units achieving?</li>
        <li>Who handles a guest complaint at 2am, and what is the response time?</li>
        <li>How often will I receive a statement, and what detail does it show?</li>
        <li>What happens if a guest damages something — deposit, insurance, or my cost?</li>
        <li>Can I block dates for my own use, and with how much notice?</li>
    </ol>
    <p>
        A manager who answers these plainly is a better sign than one who leads with a projection.
        Any operator can produce an optimistic number; far fewer can explain how they will handle
        the night something goes wrong.
    </p>

    <h2>When management makes sense</h2>
    <p>
        Self-managing works if you live near the unit, have time to answer messages promptly, and
        enjoy the operational side. It stops working when you own more than one unit, live far
        from it, travel, or simply want the income without the pager.
    </p>
    <p>
        The honest comparison is not "management fee versus no fee". It is your net after fees
        against your net self-managing — including the nights you priced wrong, the gaps you did
        not fill, and the hours you spent. For many owners the managed number is higher despite
        the fee. For some it is not. Ask for the figures that let you work out which you are.
    </p>
