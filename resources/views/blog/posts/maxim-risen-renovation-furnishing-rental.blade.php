    <h2>Decide the rental strategy before the floor plan</h2>
    <p>
        A short-stay unit for couples and small families, a monthly unit for an outstation professional and a
        corporate unit for a rotating team are three different fit-outs. Bed count, storage, kitchen equipment
        and how much of the unit is built in all follow from that choice. Make it first, then renovate.
    </p>

    <h2>What a rental fit-out gets right that a home renovation does not</h2>
