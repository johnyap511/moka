        <li><strong>Works</strong>, joinery, electrical points, lighting, finishes.</li>
        <li><strong>Furniture, appliances, linen and inventory</strong> installed and checked.</li>
        <li><strong>Photography and listing</strong> on every channel the strategy calls for.</li>
        <li><strong>First guest</strong>, with housekeeping and maintenance already in place from the EkoCheras team.</li>
    </ol>
    <p>
        The order matters: a unit furnished before the strategy is set usually needs changes before it can be
        listed, and every week it sits unlisted is rent lost.
    </p>

    <h2>Budget: where to spend and where not to</h2>
    <ul>
        <li><strong>Spend</strong> on the mattress, the sofa fabric, the water heater, the air-conditioning service and
            the lighting. Guests notice all five and reviews mention them.</li>
        <li><strong>Save</strong> on decorative pieces, premium appliances and anything a guest cannot tell apart from the
            mid-range version in a photograph.</li>
        <li><strong>Never skip</strong> the locked owner's cupboard and the housekeeping store; without them the unit
            cannot be turned over properly.</li>
    </ul>
