    <h2>Built-in joinery, not loose furniture</h2>
    <p>
        Loose furniture pushed into a compact unit moves, marks walls and photographs poorly. Built-in joinery
        fixes the layout, hides cables and storage, and survives back-to-back stays. It also makes the unit look
        larger in photographs, which is where every booking decision starts. Innspace, MOKA's renovation arm, does
        this work as a SkyWorld Solution+ panel renovator and on projects involving SkyWorld, Sunsuria and Eng Han,
        and the same standard goes into our managed units.
    </p>

